#!/usr/bin/env python3
"""Generate an image deck: slides whose weight is screenshots.

    bench/mkdeck.py DIR [--images 28] [--width 1440] [--height 900]

Writes `DIR/deck.typ` and its PNG files: by default 28 distinct images of
1440 x 900 pixels, every second one with an alpha channel, on 43 pages (a
title page and 14 slides of three steps each, as a slide that is built up
has them: an image is drawn on two or three pages, 72 times in all). No
package is used, so the deck compiles with `--ignore-system-fonts` and
nothing else.

It is the document for what an export costs when a document is images
(`tests/pdf_bench`, `docs/incremental-design.md`, slice 0): decoding,
conversion and compression are per image, and none of it depends on the
text around them. The images are synthetic screenshots: flat areas, a
gradient, lines of text-like runs and a block of noise the size of a
photograph, about 0.4 MB of compressed samples each.

Everything is a function of the arguments (no clock, a seeded generator):
two runs give the same files.
"""

import argparse
import os
import random
import struct
import zlib


def chunk(kind, data):
    body = kind + data
    return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body))


def png(width, height, channels, rows):
    """A PNG of 8-bit RGB (3 channels) or RGBA (4) rows, filter type 0."""
    raw = b"".join(b"\x00" + row for row in rows)
    header = struct.pack(">IIBBBBB", width, height, 8, 2 if channels == 3 else 6, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", header)
        + chunk(b"IDAT", zlib.compress(raw, 6))
        + chunk(b"IEND", b"")
    )


def screenshot(index, width, height, alpha):
    """The rows of a synthetic screenshot."""
    rng = random.Random(1000 + index)
    channels = 4 if alpha else 3

    def pixel(r, g, b, a=255):
        return bytes((r, g, b, a)) if alpha else bytes((r, g, b))

    accent = (rng.randrange(40, 220), rng.randrange(40, 220), rng.randrange(40, 220))
    paper = (250 - index % 7, 250 - index % 5, 248 - index % 3)
    ink = (30 + index % 11, 30 + index % 13, 40 + index % 17)
    margin = width // 18
    bar = height // 14
    line_height = max(height // 50, 6)
    # A block of noise: the photograph on the slide.
    photo_w, photo_h = width // 4, height // 3
    photo_x, photo_y = width - margin - photo_w, bar + 2 * line_height
    text_right = photo_x - margin // 2
    rows = []
    text_row = None
    for y in range(height):
        if y < bar:
            # The title bar: a horizontal gradient in the accent colour.
            row = bytearray()
            for x in range(width):
                t = x * 96 // width
                row += pixel(
                    min(accent[0] + t, 255), min(accent[1] + t // 2, 255), accent[2]
                )
            rows.append(bytes(row))
            continue
        # A translucent border on images with alpha.
        edge = 255
        if alpha and (y >= height - margin // 2):
            edge = 255 * (height - y) // (margin // 2)
        band = (y - bar) // line_height
        in_line = band % 2 == 1 and (y - bar) % line_height < line_height - 2
        if in_line:
            if (y - bar) % line_height == 0 or text_row is None:
                # A line of text: runs of ink and paper of a few pixels.
                text_row = []
                x = margin
                end = text_right - rng.randrange(0, width // 6)
                while x < end:
                    run = rng.randrange(2, 9)
                    text_row.append((x, min(x + run, end), rng.random() < 0.55))
                    x += run
        else:
            text_row = None
        row = bytearray(pixel(*paper, edge) * width)
        if text_row is not None:
            for start, stop, on in text_row:
                if on:
                    row[start * channels : stop * channels] = pixel(*ink, edge) * (
                        stop - start
                    )
        if photo_y <= y < photo_y + photo_h:
            noise = rng.randbytes(photo_w * 3)
            if alpha:
                photo = bytearray(photo_w * 4)
                photo[0::4] = noise[0::3]
                photo[1::4] = noise[1::3]
                photo[2::4] = noise[2::3]
                # The photograph fades out to the right.
                photo[3::4] = bytes(
                    min(255, 510 * (photo_w - x) // photo_w) * edge // 255
                    for x in range(photo_w)
                )
            else:
                photo = noise
            row[photo_x * channels : (photo_x + photo_w) * channels] = photo
        rows.append(bytes(row))
    return png(width, height, channels, rows)


def deck(images):
    """The source: a title page and a slide of three steps per pair."""
    out = [
        "// Generated by bench/mkdeck.py.",
        "#set page(width: 841.89pt, height: 473.56pt, margin: 28pt)",
        '#set text(size: 16pt, font: "Libertinus Serif")',
        "#let shot(name, width: 100%) = image(name, width: width)",
        "#let slide(title, body) = [",
        "  #pagebreak(weak: true)",
        "  #text(size: 24pt, weight: \"bold\", title)",
        "  #v(6pt)",
        "  #body",
        "]",
        "",
        "#align(center + horizon)[",
        "  #text(size: 34pt, weight: \"bold\")[A deck of screenshots]",
        "",
        "  %d images, each on two or three pages" % len(images),
        "  #grid(columns: 2, gutter: 12pt,",
        '    shot("%s", width: 200pt), shot("%s", width: 200pt))' % (images[0], images[1]),
        "]",
    ]
    for pair in range(len(images) // 2):
        first, second = images[2 * pair], images[2 * pair + 1]
        title = "Result %d" % (pair + 1)
        out += [
            "",
            "#slide[%s][" % title,
            '  #grid(columns: (1fr, 1fr), gutter: 14pt, shot("%s"), [])' % first,
            "]",
            "#slide[%s][" % title,
            '  #grid(columns: (1fr, 1fr), gutter: 14pt, shot("%s"), shot("%s"))'
            % (first, second),
            "]",
            "#slide[%s][" % title,
            '  #grid(columns: (1fr, 1fr), gutter: 14pt, shot("%s"), shot("%s"))'
            % (first, second),
            "  The run on the left is the baseline, the one on the right has the",
            "  change; step %d of %d." % (pair + 1, len(images) // 2),
            "]",
        ]
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("dir")
    parser.add_argument("--images", type=int, default=28, help="an even number")
    parser.add_argument("--width", type=int, default=1440)
    parser.add_argument("--height", type=int, default=900)
    options = parser.parse_args()
    if options.images < 2 or options.images % 2:
        parser.error("--images must be even and at least 2")
    os.makedirs(options.dir, exist_ok=True)
    names = []
    total = 0
    for i in range(options.images):
        name = "shot-%02d.png" % i
        data = screenshot(i, options.width, options.height, alpha=i % 2 == 1)
        with open(os.path.join(options.dir, name), "wb") as f:
            f.write(data)
        names.append(name)
        total += len(data)
    with open(os.path.join(options.dir, "deck.typ"), "w", encoding="utf-8") as f:
        f.write(deck(names))
    print(
        "%s: %d pages, %d images (%.1f MB of PNG files)"
        % (
            os.path.join(options.dir, "deck.typ"),
            1 + 3 * (options.images // 2),
            options.images,
            total / 1e6,
        )
    )


if __name__ == "__main__":
    main()
