def find_typst_assets():
    pattern = os.path.expanduser("~/.cargo/git/checkouts/typst-assets-*/94dcb99/files")
    found = sorted(glob.glob(pattern))
    if not found:
        sys.exit("typst-assets checkout not found")
    return found[-1]


def gen_pdf_fonts():
    """Embeds typst-assets' `pdf` fonts (the PDF standard font substitutes)."""
    files = find_typst_assets()
    out = [
        "// Generated by scripts/gen_hayro_tables.py from typst-assets'\n"
        "// `files/fonts/Foxit*.pfb` (`typst_assets::pdf`). Do not edit.\n\n"
    ]
    for name, file, doc in PDF_FONTS:
        data = open(os.path.join(files, "fonts", file), "rb").read()
        b64 = base64.b64encode(data).decode()
        out.append("///|\nlet %s_base64 : String =\n" % name)
        for i in range(0, len(b64), 96):
            out.append("  #|%s\n" % b64[i : i + 96])
        out.append("\n")
        out.append("///|\nlet %s_cell : Ref[Bytes?] = Ref::new(None)\n\n" % name)
        out.append(
            "///|\n/// %s\npub fn %s() -> Bytes {\n  load(%s_cell, %s_base64)\n}\n\n"
            % (doc, name, name, name)
        )
    path = os.path.join(ROOT, "typst_assets/pdf/fonts_gen.mbt")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="utf-8").write("".join(out))


def main():
    hayro = sys.argv[1] if len(sys.argv) > 1 else find_hayro()
    gen_tables(hayro)
    gen_assets(hayro)
    gen_pdf_fonts()


if __name__ == "__main__":
    main()
