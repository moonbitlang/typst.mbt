//! Generates `unicode/width_tables_gen.mbt` from `unicode-width` 0.1.14, the
//! version `codespan-reporting` 0.11.1 (typst-cli's diagnostic renderer)
//! uses for `UnicodeWidthChar::width`.
//!
//! Usage: `gen_unicode_width > unicode/width_tables_gen.mbt`

use std::fmt::Write as _;

use unicode_width::UnicodeWidthChar;

fn main() {
    // Collapse `char::width` into ranges `(lo, hi, value)` where value is
    // the width plus one (zero encodes `None`); width 1 is the default and
    // not stored.
    let mut ranges: Vec<(u32, u32, u32)> = Vec::new();
    for cp in 0u32..=0x10FFFF {
        let Some(c) = char::from_u32(cp) else { continue };
        let v = match c.width() {
            None => 0,
            Some(w) => w as u32 + 1,
        };
        if v == 2 {
            continue;
        }
        if let Some(last) = ranges.last_mut()
            && last.1 + 1 == cp
            && last.2 == v
        {
            last.1 = cp;
            continue;
        }
        ranges.push((cp, cp, v));
    }

    let mut out = String::new();
    out.push_str(
        "// Generated by oracle/src/bin/gen_unicode_width.rs from unicode-width\n\
         // 0.1.14. Do not edit.\n\n",
    );
    writeln!(
        out,
        "///|\n/// `UnicodeWidthChar::width` as `(lo, hi, width + 1)` ranges (0 = `None`);\n\
         /// characters not covered have width 1.\nlet char_width_table : FixedArray[Int] = ["
    )
    .unwrap();
    for chunk in ranges.chunks(4) {
        out.push_str("  ");
        for (a, b, v) in chunk {
            write!(out, "0x{a:X}, 0x{b:X}, {v}, ").unwrap();
        }
        out.push('\n');
    }
    out.push_str("]\n");
    print!("{out}");
}
