//! Generates unit tests of the `image`-crate-level decoding of the `codecs`
//! package from the real `image` crate, decoding exactly like upstream
//! `RasterImage::new` (`typst-library/src/visualize/image/raster.rs`):
//! `GifDecoder::new`/`WebPDecoder::new`, the (non-empty) ICC profile,
//! `set_limits(Limits::default())` and `DynamicImage::from_decoder`.
//!
//! - `codecs/image_oracle_test.mbt`: the cases of `gif_corpus.txt`,
//!   `webp_corpus.txt` and `image_corpus.txt` (`scripts/gen_image_corpus.py`;
//!   names are `<format>/<name>`): dimensions, color type, FNV-1a hash of the
//!   pixel buffer and the ICC profile's length, or the error message.
//!
//! Usage (from `oracle/`): `cargo run --release --bin gen_image_golden -- <codecs dir>`

use std::io::Cursor;
use std::path::PathBuf;

use base64::Engine;
use image::codecs::gif::GifDecoder;
use image::codecs::webp::WebPDecoder;
use image::{DynamicImage, ImageDecoder, ImageResult, Limits};

fn fnv1a(data: &[u8]) -> u64 {
    let mut h: u64 = 0xcbf29ce484222325;
    for &b in data {
        h ^= b as u64;
        h = h.wrapping_mul(0x100000001b3);
    }
    h
}

/// Upstream `RasterImage::new_impl`'s `decode`.
fn decode<T: ImageDecoder>(
    decoder: ImageResult<T>,
) -> ImageResult<(DynamicImage, Option<Vec<u8>>)> {
    let mut decoder = decoder?;
    let icc = decoder.icc_profile().ok().flatten().filter(|icc| !icc.is_empty());
    decoder.set_limits(Limits::default())?;
    let dynamic = DynamicImage::from_decoder(decoder)?;
    Ok((dynamic, icc))
}

fn describe(result: ImageResult<(DynamicImage, Option<Vec<u8>>)>) -> String {
    match result {
        Ok((dynamic, icc)) => format!(
            "{}x{} {:?} {:016x} icc={}",
            dynamic.width(),
            dynamic.height(),
            dynamic.color(),
            fnv1a(dynamic.as_bytes()),
            icc.map_or("none".to_string(), |icc| icc.len().to_string()),
        ),
        Err(err) => format!("error: {err}"),
    }
}

fn decode_gif(data: &[u8]) -> String {
    describe(decode(GifDecoder::new(Cursor::new(data))))
}

fn decode_webp(data: &[u8]) -> String {
    describe(decode(WebPDecoder::new(Cursor::new(data))))
}

fn cases(text: &str) -> Vec<(String, String)> {
    let mut cases: Vec<(String, String)> = Vec::new();
    for line in text.lines() {
        if let Some(n) = line.strip_prefix("=== ") {
            cases.push((n.trim().to_string(), String::new()));
        } else if let Some(last) = cases.last_mut() {
            last.1.push_str(line.trim());
        }
    }
    cases
}

fn escape(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

fn tests(out: &mut String, corpus: &str, prefix: Option<&str>) {
    for (name, b64) in cases(corpus) {
        let (prefix, name) = match prefix {
            Some(prefix) => (prefix, name.as_str()),
            None => name.split_once('/').expect("format prefix"),
        };
        let decode = match prefix {
            "gif" => decode_gif,
            "webp" => decode_webp,
            _ => panic!("unknown format {prefix}"),
        };
        let data = base64::engine::general_purpose::STANDARD
            .decode(&b64)
            .expect("base64");
        out.push_str(&format!(
            "\n///|\ntest \"image/{prefix}/{name}\" {{\n  assert_eq(\n    image_case(\n      \"{prefix}\",\n      \"{b64}\",\n    ),\n    \"{}\",\n  )\n}}\n",
            escape(&decode(&data))
        ));
    }
}

fn main() {
    let dir = PathBuf::from(std::env::args().nth(1).expect("codecs dir"));
    let mut s = String::from(
        "// Generated by oracle/src/bin/gen_image_golden.rs from gif_corpus.txt,\n\
         // webp_corpus.txt and image_corpus.txt. Do not edit. Expected values are the\n\
         // outputs of the real `image` crate (see `image_case` in\n\
         // raster_helpers_test.mbt).\n",
    );
    tests(&mut s, include_str!("gif_corpus.txt"), Some("gif"));
    tests(&mut s, include_str!("webp_corpus.txt"), Some("webp"));
    tests(&mut s, include_str!("image_corpus.txt"), None);
    std::fs::write(dir.join("image_oracle_test.mbt"), s).unwrap();
}
