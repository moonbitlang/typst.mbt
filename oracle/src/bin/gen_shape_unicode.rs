//! Generates `unicode/shaping_tables_gen.mbt`: the Unicode properties the
//! shaper (`shape/`, a port of rustybuzz) uses, from the very crates (and
//! versions) rustybuzz uses: General_Category (unicode-properties),
//! Script (unicode-script, mapped to ISO 15924 tags exactly like rustybuzz's
//! `CharExt::script`), Canonical_Combining_Class (unicode-ccc) and
//! Bidi_Mirroring_Glyph (unicode-bidi-mirroring).
//!
//! Usage: `gen_shape_unicode <rustybuzz src/hb dir> > unicode/shaping_tables_gen.mbt`

use std::collections::BTreeMap;
use std::fmt::Write as _;

use unicode_properties::general_category::{GeneralCategory, UnicodeGeneralCategory};
use unicode_script::UnicodeScript;

fn chars() -> impl Iterator<Item = char> {
    (0u32..=0x10FFFF).filter_map(char::from_u32)
}

/// Collapse a classification into inclusive ranges with a value. `None` is
/// the default and not stored.
fn valued(mut f: impl FnMut(char) -> Option<u32>) -> Vec<(u32, u32, u32)> {
    let mut out: Vec<(u32, u32, u32)> = Vec::new();
    for c in chars() {
        let Some(v) = f(c) else { continue };
        let cp = c as u32;
        if let Some(last) = out.last_mut()
            && last.1 + 1 == cp
            && last.2 == v
        {
            last.1 = cp;
            continue;
        }
        out.push((cp, cp, v));
    }
    out
}

fn emit_valued(out: &mut String, name: &str, doc: &str, r: &[(u32, u32, u32)]) {
    writeln!(out, "///|\n/// {doc}\nlet {name} : FixedArray[Int] = [").unwrap();
    for chunk in r.chunks(4) {
        out.push_str("  ");
        for (a, b, v) in chunk {
            write!(out, "0x{a:X}, 0x{b:X}, {v}, ").unwrap();
        }
        out.push('\n');
    }
    out.push_str("]\n\n");
}

/// rustybuzz's `hb_gc` numbering (`GeneralCategoryExt::to_rb`).
fn rb_gc(gc: GeneralCategory) -> u32 {
    use GeneralCategory::*;
    match gc {
        Control => 0,
        Format => 1,
        Unassigned => 2,
        PrivateUse => 3,
        Surrogate => 4,
        LowercaseLetter => 5,
        ModifierLetter => 6,
        OtherLetter => 7,
        TitlecaseLetter => 8,
        UppercaseLetter => 9,
        SpacingMark => 10,
        EnclosingMark => 11,
        NonspacingMark => 12,
        DecimalNumber => 13,
        LetterNumber => 14,
        OtherNumber => 15,
        ConnectorPunctuation => 16,
        DashPunctuation => 17,
        ClosePunctuation => 18,
        FinalPunctuation => 19,
        InitialPunctuation => 20,
        OtherPunctuation => 21,
        OpenPunctuation => 22,
        CurrencySymbol => 23,
        ModifierSymbol => 24,
        MathSymbol => 25,
        OtherSymbol => 26,
        LineSeparator => 27,
        ParagraphSeparator => 28,
        SpaceSeparator => 29,
    }
}

/// rustybuzz's `CharExt::script` mapping (`us::Script::X => script::Y`),
/// resolved to tags via the `script` constants in `common.rs`.
fn script_mapping(hb: &str) -> BTreeMap<String, String> {
    let common = std::fs::read_to_string(format!("{hb}/common.rs")).unwrap();
    let mut consts = BTreeMap::new();
    for line in common.lines() {
        let line = line.trim();
        if let Some(rest) = line.strip_prefix("pub const ")
            && let Some((name, rest)) = rest.split_once(": Script = Script::from_bytes(b\"")
        {
            consts.insert(name.to_string(), rest[..4].to_string());
        }
    }
    let unicode = std::fs::read_to_string(format!("{hb}/unicode.rs")).unwrap();
    let mut map = BTreeMap::new();
    for line in unicode.lines() {
        let line = line.trim();
        if let Some(rest) = line.strip_prefix("us::Script::")
            && let Some((variant, rest)) = rest.split_once(" => script::")
        {
            let name = rest.trim_end_matches(',');
            map.insert(variant.to_string(), consts[name].clone());
        }
    }
    assert!(map.len() > 150, "parsed the script mapping");
    map
}

fn main() {
    let hb = std::env::args().nth(1).expect("path to rustybuzz src/hb");
    let mapping = script_mapping(&hb);

    let mut out = String::new();
    out.push_str("// Generated by oracle/src/bin/gen_shape_unicode.rs. Do not edit.\n\n");

    emit_valued(
        &mut out,
        "rb_gc_table",
        "General_Category (unicode-properties) in rustybuzz's `hb_gc` numbering. Missing = Unassigned (2).",
        &valued(|c| {
            let v = rb_gc(c.general_category());
            (v != 2).then_some(v)
        }),
    );

    let mut tags: Vec<String> = vec!["Zzzz".into()];
    let mut unmapped = std::collections::BTreeSet::new();
    let script_values = valued(|c| {
        let name = format!("{:?}", c.script());
        let tag = match mapping.get(&name) {
            Some(tag) => tag.clone(),
            None => {
                // Scripts rustybuzz doesn't list map to UNKNOWN.
                if name != "Unknown" {
                    unmapped.insert(name);
                }
                "Zzzz".into()
            }
        };
        let idx = match tags.iter().position(|t| *t == tag) {
            Some(i) => i,
            None => {
                tags.push(tag);
                tags.len() - 1
            }
        };
        (idx != 0).then_some(idx as u32)
    });
    if !unmapped.is_empty() {
        eprintln!("scripts mapped to Zzzz by rustybuzz: {unmapped:?}");
    }
    emit_valued(
        &mut out,
        "rb_script_table",
        "Script (unicode-script) as rustybuzz maps it; value indexes `rb_script_tags`. Missing = Zzzz.",
        &script_values,
    );
    writeln!(out, "///|\nlet rb_script_tags : FixedArray[String] = [").unwrap();
    for t in &tags {
        writeln!(out, "  {t:?},").unwrap();
    }
    out.push_str("]\n\n");

    emit_valued(
        &mut out,
        "rb_ccc_table",
        "Canonical_Combining_Class (unicode-ccc). Missing = 0.",
        &valued(|c| {
            let v = unicode_ccc::get_canonical_combining_class(c) as u32;
            (v != 0).then_some(v)
        }),
    );

    let mut pairs = String::new();
    for c in chars() {
        if let Some(m) = unicode_bidi_mirroring::get_mirrored(c) {
            write!(pairs, "  0x{:X}, 0x{:X},\n", c as u32, m as u32).unwrap();
        }
    }
    writeln!(
        out,
        "///|\n/// Bidi_Mirroring_Glyph (unicode-bidi-mirroring) as sorted `[c, mirrored]` pairs.\nlet rb_mirroring_table : FixedArray[Int] = [\n{pairs}]"
    )
    .unwrap();

    print!("{out}");
}
