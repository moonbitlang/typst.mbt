//! Generates unit tests of the `codecs` raster decoders from the real crates
//! (the versions `resvg` and `image` use), decoding like `resvg`'s
//! `decode_webp`/`decode_gif`:
//!
//! - `codecs/webp_oracle_test.mbt`: the cases of `webp_corpus.txt`
//!   (`scripts/gen_webp_corpus.py`) decoded with `image-webp`
//!   (`WebPDecoder::new` + `read_image` into `output_buffer_size()` bytes):
//!   dimensions, alpha flag and FNV-1a hash of the buffer, or `error`.
//! - `codecs/gif_oracle_test.mbt`: the cases of `gif_corpus.txt`
//!   (`scripts/gen_gif_corpus.py`): the first frame decoded with the `gif`
//!   crate (`ColorOutput::RGBA`): frame size and position and FNV-1a hash of
//!   the RGBA buffer, `none` (no frame) or `error`.
//!
//! Usage (from `oracle/`): `cargo run --release --bin gen_raster_golden -- <codecs dir>`

use std::io::Cursor;
use std::path::PathBuf;

use base64::Engine;

fn fnv1a(data: &[u8]) -> u64 {
    let mut h: u64 = 0xcbf29ce484222325;
    for &b in data {
        h ^= b as u64;
        h = h.wrapping_mul(0x100000001b3);
    }
    h
}

fn decode_webp(data: &[u8]) -> String {
    let mut decoder = match image_webp::WebPDecoder::new(Cursor::new(data)) {
        Ok(d) => d,
        Err(_) => return "error".into(),
    };
    let Some(size) = decoder.output_buffer_size() else {
        return "error".into();
    };
    let mut buf = vec![0; size];
    if decoder.read_image(&mut buf).is_err() {
        return "error".into();
    }
    let (w, h) = decoder.dimensions();
    format!("{w}x{h} {} {:016x}", decoder.has_alpha(), fnv1a(&buf))
}

fn decode_gif(data: &[u8]) -> String {
    let mut options = gif::DecodeOptions::new();
    options.set_color_output(gif::ColorOutput::RGBA);
    let mut decoder = match options.read_info(data) {
        Ok(d) => d,
        Err(_) => return "error".into(),
    };
    match decoder.read_next_frame() {
        Ok(Some(frame)) => format!(
            "{}x{} at {},{} {:016x}",
            frame.width,
            frame.height,
            frame.left,
            frame.top,
            fnv1a(&frame.buffer)
        ),
        Ok(None) => "none".into(),
        Err(_) => "error".into(),
    }
}

fn cases(text: &str) -> Vec<(String, String)> {
    let mut cases: Vec<(String, String)> = Vec::new();
    for line in text.lines() {
        if let Some(n) = line.strip_prefix("=== ") {
            cases.push((n.trim().to_string(), String::new()));
        } else if let Some(last) = cases.last_mut() {
            last.1.push_str(line.trim());
        }
    }
    cases
}

fn tests(corpus: &str, prefix: &str, helper: &str, decode: fn(&[u8]) -> String) -> String {
    let mut s = format!(
        "// Generated by oracle/src/bin/gen_raster_golden.rs from {prefix}_corpus.txt. Do not edit.\n\
         // Expected values are the outputs of the real crate (see `{helper}` in\n\
         // raster_helpers_test.mbt).\n",
    );
    for (name, b64) in cases(corpus) {
        let data = base64::engine::general_purpose::STANDARD
            .decode(&b64)
            .expect("base64");
        s.push_str(&format!(
            "\n///|\ntest \"{prefix}/{name}\" {{\n  assert_eq(\n    {helper}(\n      \"{b64}\",\n    ),\n    \"{}\",\n  )\n}}\n",
            decode(&data)
        ));
    }
    s
}

fn main() {
    let dir = PathBuf::from(std::env::args().nth(1).expect("codecs dir"));
    std::fs::write(
        dir.join("webp_oracle_test.mbt"),
        tests(include_str!("webp_corpus.txt"), "webp", "webp_case", decode_webp),
    )
    .unwrap();
    std::fs::write(
        dir.join("gif_oracle_test.mbt"),
        tests(include_str!("gif_corpus.txt"), "gif", "gif_case", decode_gif),
    )
    .unwrap();
}
