//! Generates `html_assets/data_gen.mbt` from the very same `typst-assets`
//! crate upstream Typst uses for its typed HTML API (`typst_assets::html`),
//! so elements, attributes, their docs and attribute types match exactly.
//!
//! Usage: `gen_html > html_assets/data_gen.mbt && moon fmt`

use std::fmt::Write as _;

use typst_assets::html::{ATTR_STRINGS, ATTRS, ATTRS_GLOBAL, AttrInfo, ELEMS, ElemInfo, Type};

/// How many entries to emit per generated MoonBit function (keeps the
/// generated functions reasonably small for the native backend).
const CHUNK: usize = 64;

/// Escape a string as a MoonBit string literal.
fn lit(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\'' | ' ' => out.push(c),
            c if c.escape_debug().count() == 1 => out.push(c),
            c => write!(out, "\\u{{{:X}}}", c as u32).unwrap(),
        }
    }
    out.push('"');
    out
}

/// A MoonBit char literal.
fn char_lit(c: char) -> String {
    match c {
        '\'' => "'\\''".into(),
        '\\' => "'\\\\'".into(),
        c if c.escape_debug().count() == 1 => format!("'{c}'"),
        c => format!("'\\u{{{:X}}}'", c as u32),
    }
}

/// A MoonBit expression for an attribute type.
fn ty(t: &Type) -> String {
    match t {
        Type::Presence => "Presence".into(),
        Type::None => "None_".into(),
        Type::NoneEmpty => "NoneEmpty".into(),
        Type::NoneUndefined => "NoneUndefined".into(),
        Type::Auto => "Auto".into(),
        Type::TrueFalse => "TrueFalse".into(),
        Type::YesNo => "YesNo".into(),
        Type::OnOff => "OnOff".into(),
        Type::HorizontalDir => "HorizontalDir".into(),
        Type::Str => "Str".into(),
        Type::Char => "Char".into(),
        Type::Int => "Int".into(),
        Type::NonNegativeInt => "NonNegativeInt".into(),
        Type::PositiveInt => "PositiveInt".into(),
        Type::Float => "Float".into(),
        Type::PositiveFloat => "PositiveFloat".into(),
        Type::Datetime => "Datetime".into(),
        Type::Duration => "Duration".into(),
        Type::Color => "Color".into(),
        Type::IconSize => "IconSize".into(),
        Type::ImageCandidate => "ImageCandidate".into(),
        Type::SourceSize => "SourceSize".into(),
        Type::Strings(a, b) => format!("Strings({a}, {b})"),
        Type::Union(variants) => {
            let inner: Vec<_> = variants.iter().map(ty).collect();
            format!("Union([{}])", inner.join(", "))
        }
        Type::List(inner, sep, shorthand) => {
            format!("List({}, {}, {shorthand})", ty(inner), char_lit(*sep))
        }
    }
}

fn elem(e: &ElemInfo) -> String {
    let attrs: Vec<_> = e.attrs.iter().map(|i| i.to_string()).collect();
    format!(
        "ElemInfo::new({}, {}, [{}])",
        lit(e.name),
        lit(e.docs),
        attrs.join(", ")
    )
}

fn attr(a: &AttrInfo) -> String {
    format!("AttrInfo::new({}, {}, {})", lit(a.name), lit(a.docs), ty(&a.ty))
}

/// Emits a table as chunked functions pushing into an array.
fn emit_table<T>(
    out: &mut String,
    name: &str,
    item_ty: &str,
    doc: &str,
    items: &[T],
    f: impl Fn(&T) -> String,
) {
    let chunks: Vec<_> = items.chunks(CHUNK).collect();
    for (i, chunk) in chunks.iter().enumerate() {
        writeln!(out, "///|\nfn {name}_{i}(out : Array[{item_ty}]) -> Unit {{").unwrap();
        for item in chunk.iter() {
            writeln!(out, "  out.push({})", f(item)).unwrap();
        }
        out.push_str("}\n\n");
    }
    writeln!(out, "///|\nlet {name}_cell : Ref[Array[{item_ty}]?] = {{ val: None }}\n").unwrap();
    writeln!(out, "///|\n/// {doc}\npub fn {name}() -> Array[{item_ty}] {{").unwrap();
    writeln!(out, "  match {name}_cell.val {{\n    Some(t) => t\n    None => {{").unwrap();
    writeln!(out, "      let out = []").unwrap();
    for i in 0..chunks.len() {
        writeln!(out, "      {name}_{i}(out)").unwrap();
    }
    writeln!(out, "      {name}_cell.val = Some(out)\n      out\n    }}\n  }}\n}}\n").unwrap();
}

fn main() {
    let mut out = String::new();
    out.push_str(
        "// Generated by `oracle/src/bin/gen_html.rs` from the `typst-assets`\n\
         // crate used by upstream Typst (`typst_assets::html`). Do not edit.\n\n",
    );
    emit_table(&mut out, "elems", "ElemInfo", "A list of all HTML elements (`ELEMS`).", ELEMS, elem);
    emit_table(
        &mut out,
        "attrs",
        "AttrInfo",
        "A list of all elements' attributes (`ATTRS`).",
        ATTRS,
        attr,
    );
    writeln!(
        out,
        "///|\n/// The first `ATTRS_GLOBAL` attributes in `ATTRS` apply to all elements.\n\
         pub let attrs_global : Int = {ATTRS_GLOBAL}\n"
    )
    .unwrap();
    emit_table(
        &mut out,
        "attr_strings",
        "(String, String)",
        "Strings referenced by [Type::Strings] (`ATTR_STRINGS`).",
        ATTR_STRINGS,
        |(s, d)| format!("({}, {})", lit(s), lit(d)),
    );
    print!("{out}");
}
