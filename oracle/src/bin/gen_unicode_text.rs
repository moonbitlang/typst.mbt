//! Generates `unicode/text_tables_gen.mbt`: the Unicode data behind Typst's
//! `str`/`regex` functions, extracted from the very same Rust crates upstream
//! uses, so the MoonBit port matches byte-for-byte:
//!
//! - `regex-syntax`: Perl classes (`\w`, `\d`, `\s`), general categories,
//!   scripts, binary properties, property (value) aliases and simple case
//!   folding (for `(?i)`).
//! - Rust `std`: `char::to_lowercase`/`char::to_uppercase` (`lower`/`upper`).
//! - `unicode-normalization`: decompositions, compositions and canonical
//!   combining classes (`str.normalize`).
//!
//! Usage: `gen_unicode_text <regex-syntax src dir> > unicode/text_tables_gen.mbt`
//! (the source dir is needed for the property alias tables, which
//! regex-syntax does not export).

use std::collections::{BTreeMap, BTreeSet, HashMap};
use std::fmt::Write as _;

use regex_syntax::hir::{Class, ClassUnicode, ClassUnicodeRange, HirKind};

fn chars() -> impl Iterator<Item = char> {
    (0u32..=0x10FFFF).filter_map(char::from_u32)
}

/// The ranges of a regex-syntax class expression like `\p{Greek}`.
fn class_of(pat: &str) -> Vec<(u32, u32)> {
    let hir = regex_syntax::ParserBuilder::new().build().parse(pat).unwrap();
    match hir.kind() {
        HirKind::Class(Class::Unicode(c)) => {
            c.ranges().iter().map(|r| (r.start() as u32, r.end() as u32)).collect()
        }
        HirKind::Literal(lit) => {
            let c = std::str::from_utf8(&lit.0).unwrap().chars().next().unwrap();
            vec![(c as u32, c as u32)]
        }
        HirKind::Empty => vec![],
        k => panic!("unexpected hir for {pat}: {k:?}"),
    }
}

/// Collapse a classification into inclusive ranges with a value. `None` is
/// the default and not stored.
fn valued(f: impl Fn(char) -> Option<u32>) -> Vec<(u32, u32, u32)> {
    let mut out: Vec<(u32, u32, u32)> = Vec::new();
    for c in chars() {
        let Some(v) = f(c) else { continue };
        let cp = c as u32;
        if let Some(last) = out.last_mut()
            && last.1 + 1 == cp
            && last.2 == v
        {
            last.1 = cp;
            continue;
        }
        out.push((cp, cp, v));
    }
    out
}

fn emit_set(out: &mut String, name: &str, doc: &str, r: &[(u32, u32)]) {
    writeln!(out, "///|\n/// {doc}\nlet {name} : FixedArray[Int] = [").unwrap();
    for chunk in r.chunks(6) {
        out.push_str("  ");
        for (a, b) in chunk {
            write!(out, "0x{a:X}, 0x{b:X}, ").unwrap();
        }
        out.push('\n');
    }
    out.push_str("]\n\n");
}

fn emit_ints(out: &mut String, name: &str, doc: &str, r: &[u32], per_line: usize) {
    writeln!(out, "///|\n/// {doc}\nlet {name} : FixedArray[Int] = [").unwrap();
    for chunk in r.chunks(per_line) {
        out.push_str("  ");
        for v in chunk {
            write!(out, "0x{v:X}, ").unwrap();
        }
        out.push('\n');
    }
    out.push_str("]\n\n");
}

fn emit_valued(out: &mut String, name: &str, doc: &str, r: &[(u32, u32, u32)]) {
    let flat: Vec<u32> = r.iter().flat_map(|&(a, b, v)| [a, b, v]).collect();
    emit_ints(out, name, doc, &flat, 12);
}

fn emit_names(out: &mut String, name: &str, doc: &str, names: &[String]) {
    writeln!(out, "///|\n/// {doc}\nlet {name} : FixedArray[String] = [").unwrap();
    for n in names {
        writeln!(out, "  {n:?},").unwrap();
    }
    out.push_str("]\n\n");
}

/// Parse a `&[(&str, &str)]` list of string pairs.
fn string_pairs(body: &str) -> Vec<(String, String)> {
    let re = regex::Regex::new(r#"\(\s*"([^"]*)"\s*,\s*"([^"]*)"\s*\)"#).unwrap();
    re.captures_iter(body).map(|c| (c[1].to_string(), c[2].to_string())).collect()
}

/// The `(normalized alias, canonical value)` pairs of a property in
/// regex-syntax's `property_values.rs`.
fn property_values(src: &str, prop: &str) -> Vec<(String, String)> {
    let start = src.find(&format!("\"{prop}\",")).expect("property");
    let body = &src[start + prop.len() + 3..];
    let end = body.find("],").unwrap();
    string_pairs(&body[..end])
}

fn main() {
    let dir = std::env::args().nth(1).expect("path to regex-syntax src");
    let names_src =
        std::fs::read_to_string(format!("{dir}/unicode_tables/property_names.rs")).unwrap();
    let values_src =
        std::fs::read_to_string(format!("{dir}/unicode_tables/property_values.rs")).unwrap();
    let bool_src =
        std::fs::read_to_string(format!("{dir}/unicode_tables/property_bool.rs")).unwrap();

    let mut out = String::new();
    out.push_str("// Generated by oracle/src/bin/gen_unicode_text.rs. Do not edit.\n\n");

    // Perl classes.
    emit_set(&mut out, "perl_word_table", "regex-syntax `\\w`.", &class_of(r"\w"));
    emit_set(&mut out, "perl_digit_table", "regex-syntax `\\d`.", &class_of(r"\d"));
    emit_set(&mut out, "perl_space_table", "regex-syntax `\\s`.", &class_of(r"\s"));

    // Property names.
    let prop_names = string_pairs(&names_src);
    let pn: Vec<String> = prop_names.iter().flat_map(|(a, b)| [a.clone(), b.clone()]).collect();
    emit_names(
        &mut out,
        "property_name_pairs",
        "regex-syntax property names: `[alias, canonical, ...]`.",
        &pn,
    );

    // General categories.
    let gc_aliases = property_values(&values_src, "General_Category");
    let canon: BTreeSet<String> = gc_aliases.iter().map(|(_, c)| c.clone()).collect();
    let classes: BTreeMap<String, Vec<(u32, u32)>> = canon
        .iter()
        .filter(|c| !matches!(c.as_str(), "Any" | "Assigned" | "ASCII"))
        // Not supported by regex-syntax (`Surrogate`).
        .filter(|c| regex_syntax::parse(&format!(r"\p{{gc={c}}}")).is_ok())
        .map(|c| (c.clone(), class_of(&format!(r"\p{{gc={c}}}"))))
        .collect();
    let contains = |outer: &[(u32, u32)], inner: &[(u32, u32)]| {
        inner.iter().all(|&(a, b)| outer.iter().any(|&(x, y)| x <= a && b <= y))
    };
    // Leaves are the categories that contain no other non-empty category.
    let leaves: Vec<String> = classes
        .iter()
        .filter(|(n, r)| {
            !classes.iter().any(|(m, s)| m != *n && !s.is_empty() && s.len() <= r.len() && contains(r, s) && s != *r)
        })
        .map(|(n, _)| n.clone())
        .collect();
    let mut leaf_of: HashMap<u32, u32> = HashMap::new();
    for (i, leaf) in leaves.iter().enumerate() {
        for &(a, b) in &classes[leaf] {
            for c in a..=b {
                assert!(leaf_of.insert(c, i as u32).is_none(), "overlapping leaves");
            }
        }
    }
    let unassigned = leaves.iter().position(|l| l == "Unassigned").unwrap() as u32;
    emit_valued(
        &mut out,
        "gc_table",
        "General category (regex-syntax); value indexes `gc_names`. Missing = Unassigned.",
        &valued(|c| leaf_of.get(&(c as u32)).copied().filter(|&v| v != unassigned)),
    );
    emit_names(&mut out, "gc_names", "Leaf general categories.", &leaves);
    writeln!(out, "///|\nlet gc_unassigned : Int = {unassigned}\n").unwrap();
    // Groups: `[name, leaf, leaf, ..., ""]`.
    let mut groups = Vec::new();
    for (name, r) in &classes {
        if leaves.contains(name) {
            continue;
        }
        let members: Vec<usize> = leaves
            .iter()
            .enumerate()
            .filter(|(_, l)| !classes[*l].is_empty() && contains(r, &classes[*l]))
            .map(|(i, _)| i)
            .collect();
        // Count chars (ranges may span the surrogates).
        let count = |&(a, b): &(u32, u32)| (a..=b).filter(|&c| char::from_u32(c).is_some()).count();
        let total: usize =
            members.iter().flat_map(|&i| classes[&leaves[i]].iter().map(count)).sum();
        let expected: usize = r.iter().map(count).sum();
        assert_eq!(total, expected, "group {name} is not a union of leaves");
        groups.push(name.clone());
        groups.extend(members.iter().map(|i| leaves[*i].clone()));
        groups.push(String::new());
    }
    emit_names(&mut out, "gc_groups", "General category groups: `[group, leaf..., \"\"]`.", &groups);
    let gca: Vec<String> = gc_aliases.iter().flat_map(|(a, b)| [a.clone(), b.clone()]).collect();
    emit_names(&mut out, "gc_alias_pairs", "General category aliases: `[alias, canonical, ...]`.", &gca);

    // Scripts.
    let sc_aliases = property_values(&values_src, "Script");
    // Skip scripts without data (`Katakana_Or_Hiragana`).
    let sc_names: Vec<String> = sc_aliases
        .iter()
        .map(|(_, c)| c.clone())
        .collect::<BTreeSet<_>>()
        .into_iter()
        .filter(|c| regex_syntax::parse(&format!(r"\p{{sc={c}}}")).is_ok())
        .collect();
    let mut script_of: HashMap<u32, u32> = HashMap::new();
    for (i, name) in sc_names.iter().enumerate() {
        for (a, b) in class_of(&format!(r"\p{{sc={name}}}")) {
            for c in a..=b {
                assert!(script_of.insert(c, i as u32).is_none());
            }
        }
    }
    emit_valued(
        &mut out,
        "regex_script_table",
        "Script (regex-syntax, which has no data for `Unknown`); value indexes `regex_script_names`.",
        &valued(|c| script_of.get(&(c as u32)).copied()),
    );
    emit_names(&mut out, "regex_script_names", "Script names.", &sc_names);
    let sca: Vec<String> = sc_aliases.iter().flat_map(|(a, b)| [a.clone(), b.clone()]).collect();
    emit_names(&mut out, "script_alias_pairs", "Script aliases: `[alias, canonical, ...]`.", &sca);

    // Script extensions: `[offset...]` into flat ranges, indexed like
    // `regex_script_names`.
    let mut flat = Vec::new();
    let mut offsets = Vec::new();
    for name in &sc_names {
        offsets.push(flat.len() as u32);
        let r = class_of(&format!(r"\p{{scx={name}}}"));
        flat.extend(r.iter().flat_map(|&(a, b)| [a, b]));
    }
    offsets.push(flat.len() as u32);
    emit_ints(
        &mut out,
        "script_extension_offsets",
        "Start of each script's `Script_Extensions` ranges in `script_extension_table`.",
        &offsets,
        12,
    );
    emit_ints(&mut out, "script_extension_table", "Script_Extensions ranges.", &flat, 12);

    // Binary properties.
    let start = bool_src.find("BY_NAME").unwrap();
    let body = &bool_src[start..];
    let body = &body[..body.find("];").unwrap()];
    let bool_re = regex::Regex::new(r#"\("(\w+)", \w+\)"#).unwrap();
    let bool_names: Vec<String> = bool_re.captures_iter(body).map(|c| c[1].to_string()).collect();
    // Skip names that are not binary properties for the parser (`InCB`).
    let bool_names: Vec<String> = bool_names
        .into_iter()
        .filter(|n| regex_syntax::parse(&format!(r"\p{{{n}}}")).is_ok())
        .collect();
    let mut flat = Vec::new();
    let mut offsets = Vec::new();
    for name in &bool_names {
        let r = class_of(&format!(r"\p{{{name}}}"));
        offsets.push(flat.len() as u32);
        flat.extend(r.iter().flat_map(|&(a, b)| [a, b]));
    }
    offsets.push(flat.len() as u32);
    emit_names(&mut out, "bool_prop_names", "Binary properties (regex-syntax).", &bool_names);
    emit_ints(
        &mut out,
        "bool_prop_offsets",
        "Start of each binary property's ranges in `bool_prop_ranges`.",
        &offsets,
        12,
    );
    emit_ints(&mut out, "bool_prop_ranges", "Binary property ranges.", &flat, 12);

    // Simple case folding: each char maps to the next char of its orbit.
    let mut fold = Vec::new();
    for c in chars() {
        let mut cls = ClassUnicode::new([ClassUnicodeRange::new(c, c)]);
        cls.case_fold_simple();
        let orbit: Vec<u32> =
            cls.ranges().iter().flat_map(|r| r.start() as u32..=r.end() as u32).collect();
        if orbit.len() > 1 {
            let i = orbit.iter().position(|&x| x == c as u32).unwrap();
            fold.push(c as u32);
            fold.push(orbit[(i + 1) % orbit.len()]);
        }
    }
    emit_ints(
        &mut out,
        "case_fold_table",
        "Simple case folding orbits (regex-syntax): `[c, next, ...]`.",
        &fold,
        12,
    );

    // Case mappings (Rust std).
    for (name, f) in [
        ("lowercase", (|c: char| c.to_lowercase().collect::<Vec<_>>()) as fn(char) -> Vec<char>),
        ("uppercase", |c: char| c.to_uppercase().collect::<Vec<_>>()),
    ] {
        let mut single = Vec::new();
        let mut multi = Vec::new();
        for c in chars() {
            let m = f(c);
            if m.len() == 1 && m[0] == c {
                continue;
            }
            if m.len() == 1 {
                single.push(c as u32);
                single.push(m[0] as u32);
            } else {
                multi.push(c as u32);
                multi.push(m.len() as u32);
                multi.extend(m.iter().map(|&x| x as u32));
            }
        }
        emit_ints(
            &mut out,
            &format!("to_{name}_table"),
            &format!("Rust `char::to_{name}` (single char): `[c, mapped, ...]`."),
            &single,
            12,
        );
        emit_ints(
            &mut out,
            &format!("to_{name}_multi_table"),
            &format!("Rust `char::to_{name}` (multiple chars): `[c, len, chars..., ...]`."),
            &multi,
            12,
        );
    }
    emit_set(&mut out, "cased_table", "Unicode `Cased` (regex-syntax).", &class_of(r"\p{Cased}"));
    emit_set(
        &mut out,
        "case_ignorable_table",
        "Unicode `Case_Ignorable` (regex-syntax).",
        &class_of(r"\p{Case_Ignorable}"),
    );

    // Normalization (unicode-normalization).
    use unicode_normalization::char as un;
    let is_hangul = |c: char| (0xAC00..=0xD7A3).contains(&(c as u32));
    emit_valued(
        &mut out,
        "ccc_table",
        "Canonical combining class (unicode-normalization). Missing = 0.",
        &valued(|c| {
            let v = un::canonical_combining_class(c) as u32;
            (v != 0).then_some(v)
        }),
    );
    let mut canon_decomp: HashMap<char, Vec<char>> = HashMap::new();
    let mut canonical = Vec::new();
    let mut compatible = Vec::new();
    for c in chars() {
        if is_hangul(c) {
            continue;
        }
        let mut d = Vec::new();
        un::decompose_canonical(c, |x| d.push(x));
        let mut k = Vec::new();
        un::decompose_compatible(c, |x| k.push(x));
        if d != [c] {
            canonical.push(c as u32);
            canonical.push(d.len() as u32);
            canonical.extend(d.iter().map(|&x| x as u32));
        }
        if k != d {
            compatible.push(c as u32);
            compatible.push(k.len() as u32);
            compatible.extend(k.iter().map(|&x| x as u32));
        }
        canon_decomp.insert(c, d);
    }
    emit_ints(
        &mut out,
        "canonical_decomposition_table",
        "Full canonical decompositions (no Hangul): `[c, len, chars..., ...]`.",
        &canonical,
        12,
    );
    emit_ints(
        &mut out,
        "compatible_decomposition_table",
        "Full compatibility decompositions that differ from the canonical ones (no Hangul): `[c, len, chars..., ...]`.",
        &compatible,
        12,
    );
    // Compositions: every primary composite `c` with canonical decomposition
    // `(x, y)` where `full(c) = full(x) ++ [y]`.
    let mut by_decomp: HashMap<Vec<char>, Vec<char>> = HashMap::new();
    for (&c, d) in &canon_decomp {
        by_decomp.entry(d.clone()).or_default().push(c);
    }
    let mut comps = BTreeSet::new();
    for (&c, d) in &canon_decomp {
        if d.len() < 2 {
            continue;
        }
        let y = d[d.len() - 1];
        if let Some(xs) = by_decomp.get(&d[..d.len() - 1]) {
            for &x in xs {
                if un::compose(x, y) == Some(c) {
                    comps.insert((x as u32, y as u32, c as u32));
                }
            }
        }
    }
    // Sanity check: all compositions of a sample of pairs are found.
    for (&x, _) in canon_decomp.iter().filter(|(c, _)| (**c as u32) < 0x3000) {
        for y in 0x300u32..0x370 {
            let y = char::from_u32(y).unwrap();
            if let Some(c) = un::compose(x, y) {
                assert!(comps.contains(&(x as u32, y as u32, c as u32)), "missing {x:?} {y:?}");
            }
        }
    }
    let flat: Vec<u32> = comps.iter().flat_map(|&(a, b, c)| [a, b, c]).collect();
    emit_ints(
        &mut out,
        "composition_table",
        "Canonical compositions (no Hangul), sorted: `[first, second, composed, ...]`.",
        &flat,
        12,
    );

    print!("{out}");
}
