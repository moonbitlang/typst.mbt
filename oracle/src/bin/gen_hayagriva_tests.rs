struct Input {
    name: &'static str,
    kind: &'static str,
    src: String,
}

fn main() {
    let root = std::env::args().nth(1).expect("repo root");
    let assets = typst_dev_assets::get("bib/works.bib").map(|_| ()).is_some();
    assert!(assets);
    let read_asset = |p: &str| {
        String::from_utf8(typst_dev_assets::get(p).expect(p).to_vec()).unwrap()
    };
    let crate_data = |p: &str| {
        let dir = std::env::var("HAYAGRIVA_DIR").expect("HAYAGRIVA_DIR");
        std::fs::read_to_string(format!("{dir}/tests/data/{p}")).unwrap()
    };
    let inputs = vec![
        Input { name: "works_bib", kind: "bib", src: read_asset("bib/works.bib") },
        Input { name: "works_too_bib", kind: "bib", src: read_asset("bib/works_too.bib") },
        Input { name: "basic_yml", kind: "yaml", src: crate_data("basic.yml") },
        Input { name: "lotr_bib", kind: "bib", src: crate_data("lotr.bib") },
        Input { name: "disamb_yml", kind: "yaml", src: DISAMB.to_string() },
    ];

    let locale_files = locales();
    let mut out = String::new();
    writeln!(out, "// Code generated by oracle/src/bin/gen_hayagriva_tests.rs. DO NOT EDIT.")
        .unwrap();
    writeln!(out, "// Expected outputs come from the hayagriva 0.10.1 crate.").unwrap();
    for input in &inputs {
        writeln!(out).unwrap();
        writeln!(out, "///|").unwrap();
        writeln!(out, "let input_{} : String =", input.name).unwrap();
        for line in input.src.split('\n') {
            writeln!(out, "  #|{line}").unwrap();
        }
    }

    let few = [
        "ieee",
        "apa",
        "mla",
        "chicago-author-date",
        "chicago-notes",
        "harvard-cite-them-right",
        "vancouver",
        "alphanumeric",
        "nature",
        "american-chemical-society",
        "gb-7714-2015-numeric",
        "springer-basic-author-date",
    ];

    let mut count = 0;
    for input in &inputs {
        let library = match input.kind {
            "bib" => hayagriva::io::from_biblatex_str(&input.src).map_err(|e| format!("{e:?}")),
            _ => hayagriva::io::from_yaml_str(&input.src).map_err(|e| format!("{e}")),
        };
        let library = match library {
            Ok(l) => l,
            Err(e) => panic!("{}: {e}", input.name),
        };
        let keys: Vec<String> = library.iter().map(|e| e.key().to_string()).collect();
        let scenarios = vec![
            ("each", scenario_each(&keys)),
            ("mixed", scenario_mixed(&keys)),
            ("all", keys.join("|")),
        ];
        for style in ArchivedStyle::all() {
            let name = style.names()[0];
            if input.name != "works_bib" && !few.contains(&name) {
                continue;
            }
            let citationberg::Style::Independent(indep) = style.get() else {
                continue;
            };
            for (sname, spec) in &scenarios {
                if input.name == "basic_yml" && *sname != "each" {
                    continue;
                }
                let dump = run(&library, &indep, spec, &locale_files);
                writeln!(out).unwrap();
                writeln!(out, "///|").unwrap();
                writeln!(out, "test \"csl/{}/{}/{}\" {{", input.name, name, sname).unwrap();
                writeln!(out, "  let spec =").unwrap();
                for line in spec.split('\n') {
                    writeln!(out, "    #|{line}").unwrap();
                }
                writeln!(
                    out,
                    "  let dump = run_csl_case(input_{}, \"{}\", \"{}\", spec)",
                    input.name, input.kind, name
                )
                .unwrap();
                writeln!(out, "  inspect(\n    dump,\n    content=(").unwrap();
                for line in dump.split('\n') {
                    writeln!(out, "      #|{line}").unwrap();
                }
                writeln!(out, "    ),\n  )\n}}").unwrap();
                count += 1;
            }
        }
    }
    std::fs::write(format!("{root}/bib/hayagriva/csl_gen_wbtest.mbt"), out).unwrap();
    eprintln!("wrote {count} tests");

    // Loading tests (BibLaTeX and YAML, including errors).
    let mut cases: Vec<(String, &str, String)> = vec![(
        "bad_bib".into(),
        "bib",
        read_asset("bib/bad.bib"),
    )];
    for (i, src) in BIB_CASES.iter().enumerate() {
        cases.push((format!("bib_{i}"), "bib", src.to_string()));
    }
    for (i, src) in YAML_CASES.iter().enumerate() {
        cases.push((format!("yaml_{i}"), "yaml", src.to_string()));
    }
    let mut out = String::new();
    writeln!(out, "// Code generated by oracle/src/bin/gen_hayagriva_tests.rs. DO NOT EDIT.")
        .unwrap();
    writeln!(out, "// Expected outputs come from the hayagriva 0.10.1 crate.").unwrap();
    for (name, kind, src) in &cases {
        let dump = load_dump(kind, src, &locale_files);
        writeln!(out).unwrap();
        writeln!(out, "///|").unwrap();
        writeln!(out, "test \"load/{name}\" {{").unwrap();
        writeln!(out, "  let src =").unwrap();
        for line in src.split('\n') {
            writeln!(out, "    #|{line}").unwrap();
        }
        writeln!(out, "  inspect(\n    load_case(\"{kind}\", src),\n    content=(").unwrap();
        for line in dump.split('\n') {
            writeln!(out, "      #|{line}").unwrap();
        }
        writeln!(out, "    ),\n  )\n}}").unwrap();
    }
    std::fs::write(format!("{root}/bib/hayagriva/io_gen_wbtest.mbt"), out).unwrap();
    eprintln!("wrote {} load tests", cases.len());
}

/// Load a library and dump either the error or the full bibliography in two
/// styles.
fn load_dump(kind: &str, src: &str, locale_files: &[citationberg::Locale]) -> String {
    let library = match kind {
        "bib" => match hayagriva::io::from_biblatex_str(src) {
            Ok(l) => l,
            Err(errs) => {
                let mut out = String::new();
                for e in errs {
                    match e {
                        hayagriva::io::BibLaTeXError::Parse(e) => writeln!(
                            out,
                            "parse error: {} @ {}..{}",
                            e.kind, e.span.start, e.span.end
                        )
                        .unwrap(),
                        hayagriva::io::BibLaTeXError::Type(e) => writeln!(
                            out,
                            "type error: {} @ {}..{}",
                            e.kind, e.span.start, e.span.end
                        )
                        .unwrap(),
                    }
                }
                return out;
            }
        },
        _ => match hayagriva::io::from_yaml_str(src) {
            Ok(l) => l,
            Err(e) => {
                let loc = match e.location() {
                    Some(l) => format!("{}:{}:{}", l.index(), l.line(), l.column()),
                    None => "-".into(),
                };
                return format!("yaml error: {e} @ {loc}\n");
            }
        },
    };
    let keys: Vec<String> = library.iter().map(|e| e.key().to_string()).collect();
    let mut out = format!("entries: {}\n", keys.join(", "));
    if keys.is_empty() {
        return out;
    }
    for name in ["apa", "ieee", "chicago-notes"] {
        let style = ArchivedStyle::by_name(name).unwrap();
        let citationberg::Style::Independent(indep) = style.get() else { unreachable!() };
        writeln!(out, "== {name}").unwrap();
        out.push_str(&run(&library, &indep, &keys.join("|"), locale_files));
    }
    out
}

