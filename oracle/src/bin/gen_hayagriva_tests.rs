//! Generates `bib/hayagriva/csl_gen_wbtest.mbt`: rendering tests for the
//! MoonBit port of hayagriva, with expected outputs produced by the real
//! `hayagriva` crate.
//!
//! Each test loads a bibliography file, runs a citation scenario (a small
//! spec language shared with `bib/hayagriva/csl_test_helpers_wbtest.mbt`)
//! through `BibliographyDriver` with an archived style, and dumps the
//! rendered citations and bibliography in a structural text format.
//!
//! Usage: cargo run --release --bin gen_hayagriva_tests -- <repo-root>

