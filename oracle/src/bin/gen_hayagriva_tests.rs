/// Every entry cited on its own, in library order.
fn scenario_each(keys: &[String]) -> String {
    keys.join("\n")
}

/// A mix of features: multi-item citations, locators, ibid, purposes,
/// transparent locators and hidden items.
fn scenario_mixed(keys: &[String]) -> String {
    let k = |i: usize| keys[i % keys.len()].clone();
    [
        format!("{}|{};loc=page:12-15|{}", k(0), k(1), k(2)),
        format!("{};loc=page:12-15", k(1)),
        format!("{}", k(1)),
        format!("{};purpose=author", k(0)),
        format!("{};purpose=year", k(0)),
        format!("{};purpose=prose", k(3)),
        format!("{};purpose=full", k(2)),
        format!("{};tloc=sup1|{};loc=chapter:3", k(4), k(5)),
        format!("{};tloc=sup1", k(4)),
        format!("{};hidden", k(6)),
        format!("{}|{}|{}|{}", k(7), k(3), k(5), k(1)),
    ]
    .join("\n")
}

fn run(
    library: &Library,
    style: &IndependentStyle,
    spec: &str,
    locale_files: &[citationberg::Locale],
) -> String {
    let locale = LocaleCode("en-US".into());
    let mut driver = BibliographyDriver::new();
    for line in spec.split('\n') {
        if line.is_empty() {
            continue;
        }
        let mut items = Vec::new();
        for item in line.split('|') {
            let mut parts = item.split(';');
            let key = parts.next().unwrap();
            let entry: &Entry = library.get(key).unwrap();
            let mut locator = None;
            let mut hidden = false;
            let mut purpose = None;
            for opt in parts {
                if let Some(l) = opt.strip_prefix("loc=") {
                    let (kind, value) = l.split_once(':').unwrap();
                    let kind = match kind {
                        "page" => Locator::Page,
                        "chapter" => Locator::Chapter,
                        "section" => Locator::Section,
                        _ => Locator::Custom,
                    };
                    locator =
                        Some(SpecificLocator(kind, LocatorPayload::Str(value.into())));
                } else if let Some(t) = opt.strip_prefix("tloc=") {
                    locator = Some(SpecificLocator(
                        Locator::Custom,
                        LocatorPayload::Transparent(TransparentLocator::new(t.to_string())),
                    ));
                } else if let Some(p) = opt.strip_prefix("purpose=") {
                    purpose = Some(match p {
                        "author" => CitePurpose::Author,
                        "year" => CitePurpose::Year,
                        "full" => CitePurpose::Full,
                        _ => CitePurpose::Prose,
                    });
                } else if opt == "hidden" {
                    hidden = true;
                }
            }
            items.push(CitationItem::new(entry, locator, None, hidden, purpose));
        }
        driver.citation(CitationRequest::new(
            items,
            style,
            Some(locale.clone()),
            locale_files,
            None,
        ));
    }
    let rendered = driver.finish(BibliographyRequest {
        style,
        locale: Some(locale),
        locale_files,
    });
    let mut out = String::new();
    for (i, c) in rendered.citations.iter().enumerate() {
        writeln!(out, "cite {i}: {}", dump_children(&c.citation)).unwrap();
    }
    if let Some(bib) = &rendered.bibliography {
        writeln!(
            out,
            "bib: hanging={} align={} line={} entry={}",
            bib.hanging_indent,
            match bib.second_field_align {
                None => "none",
                Some(citationberg::SecondFieldAlign::Flush) => "flush",
                Some(citationberg::SecondFieldAlign::Margin) => "margin",
            },
            bib.line_spacing,
            bib.entry_spacing
        )
        .unwrap();
        for item in &bib.items {
            let first = match &item.first_field {
                Some(c) => dump_child(c),
                None => "-".into(),
            };
            writeln!(out, "[{}] {} | {}", item.key, first, dump_children(&item.content))
                .unwrap();
        }
    } else {
        writeln!(out, "bib: none").unwrap();
    }
    out
}

fn dump_fmt(f: &Formatting) -> String {
    let mut parts = Vec::new();
    match f.font_style {
        FontStyle::Normal => {}
        FontStyle::Italic => parts.push("i"),
    }
    match f.font_variant {
        FontVariant::Normal => {}
        FontVariant::SmallCaps => parts.push("sc"),
    }
    match f.font_weight {
        FontWeight::Normal => {}
        FontWeight::Bold => parts.push("b"),
        FontWeight::Light => parts.push("l"),
    }
    match f.text_decoration {
        TextDecoration::None => {}
        TextDecoration::Underline => parts.push("u"),
    }
    match f.vertical_align {
        VerticalAlign::None => {}
        VerticalAlign::Baseline => parts.push("base"),
        VerticalAlign::Sup => parts.push("sup"),
        VerticalAlign::Sub => parts.push("sub"),
    }
    if parts.is_empty() { String::new() } else { format!("{}:", parts.join(",")) }
}

fn dump_children(c: &ElemChildren) -> String {
    c.0.iter().map(dump_child).collect()
}

fn dump_child(c: &ElemChild) -> String {
    match c {
        ElemChild::Text(f) => format!("{{{}{}}}", dump_fmt(&f.formatting), f.text),
        ElemChild::Elem(e) => dump_elem(e),
        ElemChild::Markup(m) => format!("${m}$"),
        ElemChild::Link { text, url } => {
            format!("[{}{}]({})", dump_fmt(&text.formatting), text.text, url)
        }
        ElemChild::Transparent { cite_idx, format } => {
            format!("@{}{}", dump_fmt(format), cite_idx)
        }
    }
}

fn dump_elem(e: &Elem) -> String {
    let display = match e.display {
        None => "",
        Some(Display::Block) => "block",
        Some(Display::LeftMargin) => "left-margin",
        Some(Display::RightInline) => "right-inline",
        Some(Display::Indent) => "indent",
    };
    let meta = match &e.meta {
        None => String::new(),
        Some(ElemMeta::Names(_)) => "names".into(),
        Some(ElemMeta::Date) => "date".into(),
        Some(ElemMeta::Text) => "text".into(),
        Some(ElemMeta::Number) => "number".into(),
        Some(ElemMeta::Label) => "label".into(),
        Some(ElemMeta::CitationNumber) => "citation-number".into(),
        Some(ElemMeta::Name(_, i)) => format!("name:{i}"),
        Some(ElemMeta::Entry(i)) => format!("entry:{i}"),
        Some(ElemMeta::CitationLabel) => "citation-label".into(),
    };
    format!("<{display}|{meta}>{}</>", dump_children(&e.children))
}
