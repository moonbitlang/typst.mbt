//! Generates `bib/hayagriva/archive_gen.mbt`: the port of hayagriva's
//! `csl/archive.rs` (the `ArchivedStyle` enum with its names, display names
//! and CSL ids, plus the embedded styles and locales).
//!
//! Upstream embeds the styles and locales as CBOR-serialized `citationberg`
//! structs. Here, each archived style/locale is re-serialized to XML with
//! citationberg's own serializer (`Style::to_xml`, `LocaleFile::to_xml`); the
//! generator asserts that parsing that XML with `citationberg` yields exactly
//! the archived value, so the MoonBit port only needs citationberg's XML
//! deserializer.
//!
//! Usage (from `oracle/`): `cargo run --release --bin gen_csl_archive -- ..`
//! (the argument is the repository root), then `moon fmt`.

use std::fmt::Write as _;
use std::path::PathBuf;

use citationberg::{Locale, LocaleFile, Style};
use hayagriva::archive::{ArchivedStyle, locales};

/// A MoonBit string literal.
fn lit(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 || c == '\u{7f}' => {
                write!(out, "\\u{{{:x}}}", c as u32).unwrap();
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// A long MoonBit string literal, split into concatenated segments to keep
/// source lines short.
fn long_lit(s: &str) -> String {
    let chars: Vec<char> = s.chars().collect();
    let pieces: Vec<String> =
        chars.chunks(2000).map(|c| lit(&c.iter().collect::<String>())).collect();
    if pieces.is_empty() {
        return lit("");
    }
    pieces.join(" +\n      ")
}

/// The MoonBit constructor name for a style (ASCII only).
fn variant(style: ArchivedStyle) -> String {
    format!("{style:?}").replace('ü', "ue")
}

fn main() {
    let root = PathBuf::from(std::env::args().nth(1).unwrap_or_else(|| "..".into()));
    let mut out = String::new();
    out.push_str(
        "// Generated by `oracle/src/bin/gen_csl_archive.rs` from hayagriva 0.10.1's\n\
         // archive (`csl/archive.rs`). Do not edit by hand!\n\n",
    );

    let all = ArchivedStyle::all();

    // The enum.
    out.push_str("///|\n/// An embedded CSL style.\npub(all) enum ArchivedStyle {\n");
    for &s in all {
        let style = s.get();
        let authors: Vec<String> =
            style.info().authors.iter().map(|a| a.name.clone()).collect();
        writeln!(out, "  /// {}.", s.display_name()).unwrap();
        if !authors.is_empty() {
            writeln!(out, "  ///\n  /// Authors: {}.", authors.join(", ")).unwrap();
        }
        writeln!(out, "  {}", variant(s)).unwrap();
    }
    out.push_str("} derive(Eq, Hash, Debug)\n\n");

    // by_name
    out.push_str(
        "///|\n/// Retrieve this style by name.\npub fn ArchivedStyle::by_name(name : String) -> ArchivedStyle? {\n  match name {\n",
    );
    for &s in all {
        for name in s.names() {
            writeln!(out, "    {} => Some({})", lit(name), variant(s)).unwrap();
        }
    }
    out.push_str("    _ => None\n  }\n}\n\n");

    // by_id
    out.push_str(
        "///|\n/// Retrieve this style by CSL ID.\npub fn ArchivedStyle::by_id(id : String) -> ArchivedStyle? {\n  match id {\n",
    );
    for &s in all {
        writeln!(out, "    {} => Some({})", lit(s.csl_id()), variant(s)).unwrap();
    }
    out.push_str("    _ => None\n  }\n}\n\n");

    // all
    out.push_str("///|\nlet archived_style_all : ReadOnlyArray[ArchivedStyle] = [\n");
    for &s in all {
        writeln!(out, "  {},", variant(s)).unwrap();
    }
    out.push_str("]\n\n");
    out.push_str(
        "///|\n/// Get all styles in the archive.\npub fn ArchivedStyle::all() -> ReadOnlyArray[ArchivedStyle] {\n  archived_style_all\n}\n\n",
    );

    // names
    out.push_str(
        "///|\n/// Get the style's names in Hayagriva.\npub fn ArchivedStyle::names(self : ArchivedStyle) -> Array[String] {\n  match self {\n",
    );
    for &s in all {
        let names: Vec<String> = s.names().iter().map(|n| lit(n)).collect();
        writeln!(out, "    {} => [{}]", variant(s), names.join(", ")).unwrap();
    }
    out.push_str("  }\n}\n\n");

    // display_name
    out.push_str(
        "///|\n/// Get the style's full name.\npub fn ArchivedStyle::display_name(self : ArchivedStyle) -> String {\n  match self {\n",
    );
    for &s in all {
        writeln!(out, "    {} => {}", variant(s), lit(s.display_name())).unwrap();
    }
    out.push_str("  }\n}\n\n");

    // csl_id
    out.push_str(
        "///|\n/// Get the style's CSL ID.\npub fn ArchivedStyle::csl_id(self : ArchivedStyle) -> String {\n  match self {\n",
    );
    for &s in all {
        writeln!(out, "    {} => {}", variant(s), lit(s.csl_id())).unwrap();
    }
    out.push_str("  }\n}\n\n");

    // The XML of the styles.
    out.push_str(
        "///|\n/// The style's XML (serialized by citationberg from the archived style).\nfn ArchivedStyle::xml(self : ArchivedStyle) -> String {\n  match self {\n",
    );
    for &s in all {
        let style = s.get();
        let xml = style.to_xml().unwrap();
        let back = Style::from_xml(&xml).expect("archived style XML must parse");
        assert!(back == style, "XML round trip of {s:?} differs");
        writeln!(out, "    {} =>\n      {}", variant(s), long_lit(&xml)).unwrap();
    }
    out.push_str("  }\n}\n\n");

    // The locales.
    out.push_str(
        "///|\n/// The XML of the archived CSL locales (serialized by citationberg).\nlet locales_xml : ReadOnlyArray[String] = [\n",
    );
    for l in locales() {
        let file = LocaleFile::try_from(l.clone()).unwrap();
        let xml = file.to_xml().unwrap();
        let back = LocaleFile::from_xml(&xml).expect("archived locale XML must parse");
        assert!(Locale::from(back) == l, "XML round trip of locale {:?} differs", l.lang);
        writeln!(out, "  {},", long_lit(&xml)).unwrap();
    }
    out.push_str("]\n");

    let path = root.join("bib/hayagriva/archive_gen.mbt");
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(&path, out).unwrap();
    eprintln!("wrote {}", path.display());
}
