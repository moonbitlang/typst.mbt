//! Generates `unicode/tables_gen.mbt` from the very same Rust crates upstream
//! Typst uses, so character classification in the MoonBit port matches
//! byte-for-byte.
//!
//! Usage: `gen_unicode <unicode-segmentation tables.rs> > unicode/tables_gen.mbt`

use std::collections::BTreeMap;
use std::fmt::Write as _;

use unicode_script::UnicodeScript;

fn chars() -> impl Iterator<Item = char> {
    (0u32..=0x10FFFF).filter_map(char::from_u32)
}

/// Collapse a predicate into inclusive ranges.
fn ranges(pred: impl Fn(char) -> bool) -> Vec<(u32, u32)> {
    valued(|c| pred(c).then_some(1u32)).into_iter().map(|(a, b, _)| (a, b)).collect()
}

/// Collapse a classification into inclusive ranges with a value. `None` is
/// the default and not stored.
fn valued(f: impl Fn(char) -> Option<u32>) -> Vec<(u32, u32, u32)> {
    let mut out: Vec<(u32, u32, u32)> = Vec::new();
    for c in chars() {
        let Some(v) = f(c) else { continue };
        let cp = c as u32;
        if let Some(last) = out.last_mut()
            && last.1 + 1 == cp
            && last.2 == v
        {
            last.1 = cp;
            continue;
        }
        out.push((cp, cp, v));
    }
    out
}

fn emit_set(out: &mut String, name: &str, doc: &str, r: &[(u32, u32)]) {
    writeln!(out, "///|\n/// {doc}\nlet {name} : FixedArray[Int] = [").unwrap();
    for chunk in r.chunks(6) {
        out.push_str("  ");
        for (a, b) in chunk {
            write!(out, "0x{a:X}, 0x{b:X}, ").unwrap();
        }
        out.push('\n');
    }
    out.push_str("]\n\n");
}

fn emit_valued(out: &mut String, name: &str, doc: &str, r: &[(u32, u32, u32)]) {
    writeln!(out, "///|\n/// {doc}\nlet {name} : FixedArray[Int] = [").unwrap();
    for chunk in r.chunks(4) {
        out.push_str("  ");
        for (a, b, v) in chunk {
            write!(out, "0x{a:X}, 0x{b:X}, {v}, ").unwrap();
        }
        out.push('\n');
    }
    out.push_str("]\n\n");
}

fn emit_names(out: &mut String, name: &str, names: &[String]) {
    writeln!(out, "///|\nlet {name} : FixedArray[String] = [").unwrap();
    for n in names {
        writeln!(out, "  {n:?},").unwrap();
    }
    out.push_str("]\n\n");
}

/// Parse `grapheme_cat_table` out of unicode-segmentation's `tables.rs`.
fn grapheme_table(src: &str) -> (Vec<(u32, u32, u32)>, Vec<String>) {
    let start = src.find("const grapheme_cat_table").expect("grapheme table");
    let start = start + src[start..].find("= &[").unwrap();
    let body = &src[start..];
    let body = &body[..body.find("];").unwrap()];
    let mut names: Vec<String> = vec!["GC_Any".into()];
    let mut out = Vec::new();
    for item in body.split("('").skip(1) {
        // item: \u{0}', '\u{9}', GC_Control), ...
        let parts: Vec<&str> = item.splitn(3, ',').collect();
        let parse = |s: &str| {
            let s = s.trim().trim_matches('\'');
            let hex = s.trim_start_matches("\\u{").trim_end_matches('}');
            u32::from_str_radix(hex, 16).unwrap()
        };
        let lo = parse(parts[0]);
        let hi = parse(parts[1]);
        let cat = parts[2].trim();
        let cat = &cat[..cat.find(')').unwrap()];
        let idx = match names.iter().position(|n| n == cat) {
            Some(i) => i,
            None => {
                names.push(cat.to_string());
                names.len() - 1
            }
        };
        out.push((lo, hi, idx as u32));
    }
    (out, names)
}

/// Parse a `const <name>: &[(char, char)]` table out of `tables.rs`.
fn char_range_table(src: &str, name: &str) -> Vec<(u32, u32)> {
    let start = src.find(&format!("const {name}")).expect("table");
    let start = start + src[start..].find("= &[").unwrap();
    let body = &src[start..];
    let body = &body[..body.find("];").unwrap()];
    let parse = |s: &str| {
        let s = s.trim().trim_matches(|c| c == '\'' || c == ')' || c == '(');
        let hex = s.trim_start_matches("\\u{").trim_end_matches('}');
        u32::from_str_radix(hex, 16).unwrap()
    };
    body.split("('")
        .skip(1)
        .map(|item| {
            let mut parts = item.splitn(3, ',');
            (parse(parts.next().unwrap()), parse(parts.next().unwrap()))
        })
        .collect()
}

fn debug_escapes(c: char, prefix: &str) -> bool {
    let s = format!("{prefix}{c}");
    let dbg = format!("{s:?}");
    dbg != format!("\"{s}\"") || matches!(c, '"' | '\\')
}

fn main() {
    let tables_rs = std::env::args().nth(1).expect("path to unicode-segmentation tables.rs");
    let seg_src = std::fs::read_to_string(tables_rs).unwrap();

    let mut out = String::new();
    out.push_str("// Generated by oracle/src/bin/gen_unicode.rs. Do not edit.\n\n");

    emit_set(&mut out, "xid_start_table", "XID_Start (unicode-ident).", &ranges(unicode_ident::is_xid_start));
    emit_set(&mut out, "xid_continue_table", "XID_Continue (unicode-ident).", &ranges(unicode_ident::is_xid_continue));
    emit_set(&mut out, "white_space_table", "Rust `char::is_whitespace`.", &ranges(char::is_whitespace));
    emit_set(&mut out, "alphabetic_table", "Rust `char::is_alphabetic`.", &ranges(char::is_alphabetic));
    emit_set(&mut out, "numeric_table", "Rust `char::is_numeric`.", &ranges(char::is_numeric));
    emit_set(&mut out, "lowercase_table", "Rust `char::is_lowercase`.", &ranges(char::is_lowercase));
    emit_set(&mut out, "uppercase_table", "Rust `char::is_uppercase`.", &ranges(char::is_uppercase));
    emit_set(&mut out, "control_table", "Rust `char::is_control`.", &ranges(char::is_control));
    emit_set(
        &mut out,
        "debug_escape_table",
        "Characters escaped by Rust's `Debug for str` when not at the start.",
        &ranges(|c| debug_escapes(c, "a")),
    );
    emit_set(
        &mut out,
        "debug_escape_first_table",
        "Characters escaped by Rust's `Debug for str` at the start of a string.",
        &ranges(|c| debug_escapes(c, "")),
    );

    // Characters whose writing system does not use spaces, as determined by
    // `codex::space_discarding` (its `writing_system_spacing` is private, but
    // `discard_space_between(c, "")` is true exactly for those characters).
    emit_set(
        &mut out,
        "no_space_writing_table",
        "Characters with `WritingSystemSpacing::No` (codex `space_discarding`).",
        &ranges(|c| codex::space_discarding::discard_space_between(&c.to_string(), "")),
    );

    // Scripts.
    let mut script_names: BTreeMap<String, u32> = BTreeMap::new();
    for c in chars() {
        let name = format!("{:?}", c.script());
        let n = script_names.len() as u32;
        script_names.entry(name).or_insert(n);
    }
    let mut names = vec![String::new(); script_names.len()];
    for (name, &i) in &script_names {
        names[i as usize] = name.clone();
    }
    let unknown = script_names["Unknown"];
    emit_valued(
        &mut out,
        "script_table",
        "Script property (unicode-script); value indexes `script_names`. Missing = Unknown.",
        &valued(|c| {
            let v = script_names[&format!("{:?}", c.script())];
            (v != unknown).then_some(v)
        }),
    );
    emit_names(&mut out, "script_names", &names);
    writeln!(out, "///|\nlet script_unknown : Int = {unknown}\n").unwrap();

    // Math classes (with Typst's overrides).
    let classes = [
        "Normal", "Alphabetic", "Binary", "Closing", "Diacritic", "Fence", "GlyphPart",
        "Large", "Opening", "Punctuation", "Relation", "Space", "Unary", "Vary", "Special",
    ];
    emit_valued(
        &mut out,
        "math_class_table",
        "typst_utils::default_math_class; value indexes `math_class_names`.",
        &valued(|c| {
            typst_utils::default_math_class(c).map(|mc| {
                let name = format!("{mc:?}");
                classes.iter().position(|n| *n == name).unwrap() as u32
            })
        }),
    );

    // Grapheme cluster break categories.
    let (gc, gc_names) = grapheme_table(&seg_src);
    emit_valued(
        &mut out,
        "grapheme_cat_table",
        "Grapheme categories (unicode-segmentation 1.12); value indexes `grapheme_cat_names`.",
        &gc,
    );
    emit_names(&mut out, "grapheme_cat_names", &gc_names);
    emit_set(
        &mut out,
        "incb_extend_table",
        "InCB=Extend (unicode-segmentation 1.12).",
        &char_range_table(&seg_src, "InCB_Extend_table"),
    );

    print!("{out}");
}
