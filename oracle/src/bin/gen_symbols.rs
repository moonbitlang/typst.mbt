//! Generates `library/symbols_gen.mbt` from the very same `codex` crate
//! upstream Typst uses for its `sym` and `emoji` modules, so symbol names,
//! variants (in order) and deprecations match exactly.
//!
//! Usage: `gen_symbols > library/symbols_gen.mbt && moon fmt`

use std::fmt::Write as _;

/// How many bindings to emit per generated MoonBit function (keeps the
/// generated functions reasonably small for the native backend).
const CHUNK: usize = 64;

/// Escape a string as a MoonBit string literal.
fn lit(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            // Keep printable characters verbatim for readability, escape
            // everything Rust's `escape_debug` would escape (controls,
            // grapheme extenders such as combining marks or variation
            // selectors, whitespace other than ' ', ...).
            '\'' | ' ' => out.push(c),
            c if c.escape_debug().count() == 1 => out.push(c),
            c => write!(out, "\\u{{{:X}}}", c as u32).unwrap(),
        }
    }
    out.push('"');
    out
}

fn opt(s: Option<&str>) -> String {
    match s {
        Some(s) => format!("Some({})", lit(s)),
        None => "None".into(),
    }
}

/// Emits a module as a set of functions. Returns the name of the function
/// producing the module.
fn emit_module(out: &mut String, fn_name: &str, doc: &str, module: codex::Module) {
    let entries: Vec<_> = module.iter().collect();
    let mut nested = Vec::new();
    let chunks: Vec<_> = entries.chunks(CHUNK).collect();
    for (i, chunk) in chunks.iter().enumerate() {
        writeln!(out, "///|\nfn {fn_name}_{i}(out : Array[(String, CodexBinding)]) -> Unit {{")
            .unwrap();
        for (name, binding) in chunk.iter() {
            let def = match binding.def {
                codex::Def::Symbol(codex::Symbol::Single(value)) => {
                    format!("Symbol(Single({}))", lit(value))
                }
                codex::Def::Symbol(sym @ codex::Symbol::Multi(_)) => {
                    let mut s = String::from("Symbol(\n      Multi([\n");
                    for (modifiers, value, deprecation) in sym.variants() {
                        writeln!(
                            s,
                            "        (ModifierSet::from_raw_dotted({}), {}, {}),",
                            lit(modifiers.as_str()),
                            lit(value),
                            opt(deprecation),
                        )
                        .unwrap();
                    }
                    s.push_str("      ]),\n    )");
                    s
                }
                codex::Def::Module(m) => {
                    let sub = format!("{fn_name}_{name}");
                    nested.push((sub.clone(), *name, m));
                    format!("Module({sub}())")
                }
            };
            writeln!(
                out,
                "  out.push(({}, {{ def: {def}, deprecation: {} }}))",
                lit(name),
                opt(binding.deprecation),
            )
            .unwrap();
        }
        out.push_str("}\n\n");
    }

    writeln!(out, "///|\n/// {doc}\nfn {fn_name}() -> CodexModule {{").unwrap();
    writeln!(out, "  let out = []").unwrap();
    for i in 0..chunks.len() {
        writeln!(out, "  {fn_name}_{i}(out)").unwrap();
    }
    out.push_str("  CodexModule(out)\n}\n\n");

    for (sub, name, m) in nested {
        emit_module(out, &sub, &format!("The `{name}` submodule."), m);
    }
}

fn main() {
    let mut out = String::new();
    out.push_str(
        "// Generated by `oracle/src/bin/gen_symbols.rs` from the `codex` crate\n\
         // used by upstream Typst. Do not edit.\n\n",
    );
    emit_module(&mut out, "codex_sym_data", "Named general symbols (`codex::SYM`).", codex::SYM);
    emit_module(&mut out, "codex_emoji_data", "Named emoji (`codex::EMOJI`).", codex::EMOJI);
    print!("{out}");
}
