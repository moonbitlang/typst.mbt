fn gen_hypher(krate: &Path, dest: &Path) {
    let src = std::fs::read_to_string(krate.join("src/lang.rs")).unwrap();
    let mut out = String::from(HEADER);

    // Variants in declaration order.
    let enum_body = &src[src.find("pub enum Lang {").unwrap()..];
    let enum_body = &enum_body[..enum_body.find('}').unwrap()];
    let variants: Vec<String> = enum_body
        .lines()
        .map(str::trim)
        .filter(|l| l.ends_with(',') && !l.starts_with('#'))
        .map(|l| l.trim_end_matches(',').to_string())
        .collect();

    let section = |start: &str| -> &str {
        let s = &src[src.find(start).unwrap()..];
        &s[..s.find("\n    }\n").unwrap()]
    };

    // from_iso
    let mut iso = Vec::new();
    for line in section("pub fn from_iso").lines() {
        let line = line.trim();
        if let Some(rest) = line.strip_prefix("b\"") {
            let code = &rest[..2];
            let var = &line[line.find("Self::").unwrap() + 6..line.rfind(')').unwrap()];
            iso.push((code.to_string(), var.to_string()));
        }
    }
    // bounds
    let mut bounds = Vec::new();
    for line in section("pub fn bounds").lines() {
        let line = line.trim();
        if let Some(rest) = line.strip_prefix("Self::") {
            let var = &rest[..rest.find(' ').unwrap()];
            let tuple = &rest[rest.find('(').unwrap() + 1..rest.find(')').unwrap()];
            let (l, r) = tuple.split_once(", ").unwrap();
            bounds.push((var.to_string(), l.to_string(), r.to_string()));
        }
    }
    assert_eq!(bounds.len(), variants.len());
    // hyphenation_character
    let mut no_hyphen = Vec::new();
    let hc = section("pub fn hyphenation_character");
    assert!(hc.contains("_ => Some('\\u{ad}')"));
    for line in hc.lines() {
        let line = line.trim();
        if let Some(rest) = line.strip_prefix("Self::") {
            assert!(rest.ends_with("=> None,"));
            no_hyphen.push(rest[..rest.find(' ').unwrap()].to_string());
        }
    }
    // root
    let mut files = Vec::new();
    for line in section("fn root").lines() {
        let line = line.trim();
        if let Some(rest) = line.strip_prefix("Self::") {
            let var = &rest[..rest.find(' ').unwrap()];
            let file = &rest[rest.find("tries/").unwrap() + 6..rest.find(".bin").unwrap()];
            files.push((var.to_string(), file.to_string()));
        }
    }
    assert_eq!(files.len(), variants.len());

    out.push_str("///|\n/// A language that can be hyphenated (hypher 0.1.8).\npub(all) enum Lang {\n");
    for v in &variants {
        writeln!(out, "  {v}").unwrap();
    }
    out.push_str("} derive(Eq, Hash, Debug)\n\n");

    out.push_str(
        "///|\n/// Select a language using its two-letter ISO 639-1 code.\npub fn Lang::from_iso(code : String) -> Lang? {\n  match code {\n",
    );
    for (code, var) in &iso {
        writeln!(out, "    {code:?} => Some({var})").unwrap();
    }
    out.push_str("    _ => None\n  }\n}\n\n");

    out.push_str(
        "///|\n/// The default number of chars to each side between which no hyphenation\n/// should happen.\npub fn Lang::bounds(self : Lang) -> (Int, Int) {\n  match self {\n",
    );
    for (var, l, r) in &bounds {
        writeln!(out, "    {var} => ({l}, {r})").unwrap();
    }
    out.push_str("  }\n}\n\n");

    out.push_str(
        "///|\n/// The hyphenation character used by the language, if any.\npub fn Lang::hyphenation_character(self : Lang) -> Char? {\n  match self {\n",
    );
    for var in &no_hyphen {
        writeln!(out, "    {var} => None").unwrap();
    }
    out.push_str("    _ => Some('\\u{ad}')\n  }\n}\n\n");

    out.push_str("///|\n/// Index of the language's trie in `tries`.\nfn Lang::index(self : Lang) -> Int {\n  match self {\n");
    for (k, v) in variants.iter().enumerate() {
        writeln!(out, "    {v} => {k}").unwrap();
    }
    out.push_str("  }\n}\n\n");

    out.push_str("///|\n/// The embedded tries (base64), indexed by `Lang::index`.\nlet tries : FixedArray[String] = [\n");
    for v in &variants {
        let file = &files.iter().find(|(f, _)| f == v).unwrap().1;
        writeln!(out, "  trie_{file},").unwrap();
    }
    out.push_str("]\n\n");

    for (_, file) in &files {
        let data = std::fs::read(krate.join(format!("tries/{file}.bin"))).unwrap();
        emit_blob(&mut out, &format!("trie_{file}"), &format!("`tries/{file}.bin`"), &data);
    }
    write(dest, &out);
}
