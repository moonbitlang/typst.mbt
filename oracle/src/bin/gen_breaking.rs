// icu_segmenter / icu_properties.

fn break_state_byte(s: BreakState) -> u8 {
    match s {
        BreakState::Break => 253,
        BreakState::Keep => 255,
        BreakState::NoMatch => 254,
        BreakState::Intermediate(i) => i + 120,
        BreakState::Index(i) => i,
    }
}

fn emit_rule_data(out: &mut String, prefix: &str, doc: &str, data: &RuleBreakData) {
    emit_valued(
        out,
        &format!("{prefix}_property_table"),
        &format!("{doc}: `property_table` as ranges. Missing = 0."),
        &valued(|cp| data.property_table.get32(cp) as u32, 0),
    );
    let states: Vec<i64> =
        data.break_state_table.iter().map(|s| break_state_byte(s) as i64).collect();
    emit_ints(
        out,
        &format!("{prefix}_break_state_table"),
        &format!("{doc}: `break_state_table` (ULE bytes)."),
        "Int",
        &states,
    );
    writeln!(
        out,
        "///|\nlet {prefix}_params : (Int, Int, Int, Int, Int) = ({}, {}, {}, {}, {})\n",
        data.property_count,
        data.last_codepoint_property,
        data.sot_property,
        data.eot_property,
        data.complex_property,
    )
    .unwrap();
    assert!(data.rule_status_table.is_empty() || !data.rule_status_table.is_empty());
}

fn gen_linebreak(data_crate: &Path, dest: &Path, lstm_dest: &Path) {
    let mut out = String::from(HEADER);

    // Baked line break data (used by `LineSegmenter::new_lstm`).
    let resp: DataResponse<SegmenterBreakLineV1> = Baked.load(Default::default()).unwrap();
    emit_rule_data(&mut out, "line", "Baked `SegmenterBreakLineV1`", resp.payload.get());

    // Typst's custom CJ data.
    let blob =
        BlobDataProvider::try_new_from_static_blob(typst_assets::icu::ICU_CJ_SEGMENT).unwrap();
    let resp: DataResponse<SegmenterBreakLineV1> =
        blob.as_deserializing().load(Default::default()).unwrap();
    emit_rule_data(
        &mut out,
        "cj_line",
        "`SegmenterBreakLineV1` from `typst_assets::icu::ICU_CJ_SEGMENT`",
        resp.payload.get(),
    );

    // The `Line_Break` property (icu_properties).
    let names = PropertyNamesShort::<LineBreak>::new();
    let map = CodePointMapData::<LineBreak>::new();
    let mut lb_names: Vec<String> = Vec::new();
    for v in 0u8..=255 {
        #[allow(deprecated)]
        let lb = LineBreak::from_icu4c_value(v);
        match names.get(lb) {
            Some(n) => {
                assert_eq!(lb_names.len(), v as usize);
                lb_names.push(n.to_string());
            }
            None => break,
        }
    }
    #[allow(deprecated)]
    let table = valued(|cp| map.get32(cp).to_icu4c_value() as u32, 0);
    emit_valued(
        &mut out,
        "line_break_table",
        "`Line_Break` (icu_properties 2.3); values are ICU4C `ULineBreak` values. Missing = XX (0).",
        &table,
    );
    emit_names(&mut out, "line_break_names", &lb_names);
    write(dest, &out);

    // LSTM models.
    let src =
        std::fs::read_to_string(data_crate.join("data/segmenter_lstm_auto_v1.rs.data")).unwrap();
    let mut out = String::from(HEADER);
    let trie_start = src.find("ZeroTrieSimpleAscii { store: b\"").unwrap() + 31;
    let (trie, _) = parse_byte_str(&src[trie_start..]);
    let names = trie_names(&trie);
    let models: Vec<&str> =
        src.split("LstmDataFloat32::from_parts_unchecked(").skip(1).collect();
    assert_eq!(models.len(), names.len());
    for (name, idx) in &names {
        let model = models[*idx];
        let script = name.split('_').next().unwrap().to_lowercase();
        let kind = if model.trim_start().starts_with("icu::segmenter::provider::ModelType::Codepoints")
        {
            "Codepoints"
        } else {
            "GraphemeClusters"
        };
        // Byte strings in order: dic keys, dic values, then 9 matrices.
        let mut rest = model;
        let mut blobs = Vec::new();
        let mut dims = Vec::new();
        while let Some(i) = rest.find("from_bytes_unchecked(b\"") {
            let before = &rest[..i];
            if let Some(d) = before.rfind("from_parts_unchecked([") {
                let d = &before[d + 22..];
                let d = &d[..d.find(']').unwrap()];
                dims.push(
                    d.split(',')
                        .map(|x| x.trim().trim_end_matches("u16").parse::<usize>().unwrap())
                        .collect::<Vec<_>>(),
                );
            } else {
                dims.push(vec![]);
            }
            let (bytes, consumed) = parse_byte_str(&rest[i + 23..]);
            blobs.push(bytes);
            rest = &rest[i + 23 + consumed..];
            if blobs.len() == 11 {
                break;
            }
        }
        assert_eq!(blobs.len(), 11);
        let keys = varzerovec16(&blobs[0]);
        let values: Vec<u16> =
            blobs[1].chunks(2).map(|c| u16::from_le_bytes([c[0], c[1]])).collect();
        assert_eq!(keys.len(), values.len());
        writeln!(out, "///|\n/// `{name}` ({kind}).").unwrap();
        writeln!(out, "let {script}_model_type : String = {kind:?}\n").unwrap();
        writeln!(out, "///|\nlet {script}_dic : FixedArray[(String, Int)] = [").unwrap();
        for (k, v) in keys.iter().zip(&values) {
            writeln!(out, "  ({k:?}, {v}),").unwrap();
        }
        out.push_str("]\n\n");
        let mat_names =
            ["embedding", "fw_w", "fw_u", "fw_b", "bw_w", "bw_u", "bw_b", "time_w", "time_b"];
        for (k, mname) in mat_names.iter().enumerate() {
            let d = &dims[k + 2];
            assert_eq!(d.iter().product::<usize>() * 4, blobs[k + 2].len(), "{name} {mname}");
            writeln!(
                out,
                "///|\nlet {script}_{mname}_dims : FixedArray[Int] = {:?}\n",
                d
            )
            .unwrap();
            emit_blob(
                &mut out,
                &format!("{script}_{mname}_data"),
                &format!("`{mname}` of `{name}`, little-endian f32"),
                &blobs[k + 2],
            );
        }
    }
    write(lstm_dest, &out);
}

/// Parse a Rust byte string literal body (after the opening `b"`), returning
/// the bytes and the number of source bytes consumed including the closing
/// quote.
fn parse_byte_str(s: &str) -> (Vec<u8>, usize) {
    let b = s.as_bytes();
    let mut out = Vec::new();
    let mut i = 0;
    loop {
        match b[i] {
            b'"' => return (out, i + 1),
            b'\\' => {
                i += 1;
                match b[i] {
                    b'x' => {
                        let hex = std::str::from_utf8(&b[i + 1..i + 3]).unwrap();
                        out.push(u8::from_str_radix(hex, 16).unwrap());
                        i += 3;
                    }
                    b'0' => {
                        out.push(0);
                        i += 1;
                    }
                    b't' => {
                        out.push(b'\t');
                        i += 1;
                    }
                    b'n' => {
                        out.push(b'\n');
                        i += 1;
                    }
                    b'r' => {
                        out.push(b'\r');
                        i += 1;
                    }
                    b'\\' | b'"' | b'\'' => {
                        out.push(b[i]);
                        i += 1;
                    }
                    other => panic!("unknown escape \\{}", other as char),
                }
            }
            c => {
                out.push(c);
                i += 1;
            }
        }
    }
}

/// Decode a `VarZeroVec16<PotentialUtf8>`: `len: u16`, `len - 1` u16 start
/// indices of elements `1..len`, then the concatenated element bytes.
fn varzerovec16(b: &[u8]) -> Vec<String> {
    let len = u16::from_le_bytes([b[0], b[1]]) as usize;
    if len == 0 {
        return vec![];
    }
    let header = 2 + 2 * (len - 1);
    let data = &b[header..];
    let mut starts = vec![0usize];
    for k in 0..len - 1 {
        starts.push(u16::from_le_bytes([b[2 + 2 * k], b[3 + 2 * k]]) as usize);
    }
    starts.push(data.len());
    (0..len)
        .map(|k| String::from_utf8(data[starts[k]..starts[k + 1]].to_vec()).unwrap())
        .collect()
}

/// Enumerate the `(name, value)` pairs of a baked `ZeroTrieSimpleAscii` that
/// maps `und\x1E<attributes>` identifiers to value indices. Only the shapes
/// used by the LSTM data (ASCII runs, value nodes and one branch node with a
/// linear lookup table) are supported.
fn trie_names(trie: &[u8]) -> Vec<(String, usize)> {
    let mut out = Vec::new();
    walk_trie(trie, 0, String::new(), &mut out);
    out.into_iter()
        .map(|(k, v)| (k.split('\x1E').nth(1).unwrap().to_string(), v))
        .collect()
}

fn walk_trie(t: &[u8], mut i: usize, mut prefix: String, out: &mut Vec<(String, usize)>) {
    while i < t.len() {
        let b = t[i];
        if b < 0x80 {
            prefix.push(b as char);
            i += 1;
        } else if b & 0xE0 == 0x80 {
            // Value node (small values only).
            assert!(b & 0x10 == 0);
            out.push((prefix.clone(), (b & 0x0F) as usize));
            return;
        } else if b & 0xC0 == 0xC0 {
            // Branch node: `0b11xxxxxx` with x = number of branches (small),
            // followed by the ASCII keys and one-byte offsets.
            assert!(b & 0x20 == 0);
            let n = (b & 0x1F) as usize;
            let keys = &t[i + 1..i + 1 + n];
            let offsets = &t[i + 1 + n..i + 1 + n + (n - 1)];
            let base = i + 1 + n + (n - 1);
            for k in 0..n {
                let start = if k == 0 { 0 } else { offsets[k - 1] as usize };
                let mut p = prefix.clone();
                p.push(keys[k] as char);
                walk_trie(t, base + start, p, out);
            }
            return;
        } else {
            panic!("unsupported trie node {b:#x}");
        }
    }
}

