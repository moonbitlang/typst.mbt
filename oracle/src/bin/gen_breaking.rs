// unicode-segmentation (word boundaries).

fn gen_word(krate: &Path, dest: &Path) {
    let src = std::fs::read_to_string(krate.join("src/tables.rs")).unwrap();
    let mut out = String::from(HEADER);
    let mut names: Vec<String> = vec!["WC_Any".into()];
    let table: Vec<(u32, u32, u32)> = rust_table(&src, "word_cat_table")
        .iter()
        .map(|t| {
            let cat = tok_word(&t[2]).to_string();
            let idx = match names.iter().position(|n| *n == cat) {
                Some(i) => i,
                None => {
                    names.push(cat);
                    names.len() - 1
                }
            };
            (tok_char(&t[0]), tok_char(&t[1]), idx as u32)
        })
        .collect();
    emit_valued(
        &mut out,
        "word_cat_table",
        "Word break categories (unicode-segmentation 1.12); value indexes `word_cat_names`.",
        &table,
    );
    emit_names(&mut out, "word_cat_names", &names);
    let emoji: Vec<(u32, u32, u32)> = rust_table(&src, "emoji_cat_table")
        .iter()
        .map(|t| {
            assert_eq!(tok_word(&t[2]), "EC_Extended_Pictographic");
            (tok_char(&t[0]), tok_char(&t[1]), 1)
        })
        .collect();
    emit_valued(
        &mut out,
        "emoji_cat_table",
        "Extended_Pictographic (unicode-segmentation 1.12 `emoji_cat_table`).",
        &emoji,
    );
    for (name, rust) in [("seg_alphabetic_table", "Alphabetic_table"), ("seg_n_table", "N_table")] {
        let r: Vec<(u32, u32, u32)> = rust_table(&src, rust)
            .iter()
            .map(|t| (tok_char(&t[0]), tok_char(&t[1]), 1))
            .collect();
        emit_valued(
            &mut out,
            name,
            &format!("`{rust}` (unicode-segmentation 1.12)."),
            &r,
        );
    }
    write(dest, &out);
}

