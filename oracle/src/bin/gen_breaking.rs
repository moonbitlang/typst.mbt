//! Generates the data tables of the MoonBit `bidi`, `linebreak` and `hypher`
//! packages (plus the word-boundary tables of `unicode`) from the very same
//! crates upstream Typst uses:
//!
//! - `unicode-bidi 0.3.18`: `bidi_class_table` and `bidi_pairs_table`, parsed
//!   out of `src/char_data/tables.rs`.
//! - `icu_segmenter 2.3.0`: the baked `SegmenterBreakLineV1` rule data (via
//!   the public provider API), the same data from Typst's custom CJ blob
//!   (`typst_assets::icu::ICU_CJ_SEGMENT`) and the four LSTM models, parsed
//!   out of `icu_segmenter_data`'s baked `segmenter_lstm_auto_v1.rs.data`.
//! - `icu_properties 2.3.0`: the `Line_Break` property map.
//! - `unicode-segmentation 1.12.0`: word break categories and the
//!   `Extended_Pictographic` table, parsed out of `src/tables.rs`.
//! - `hypher 0.1.8`: the embedded pattern tries (`tries/*.bin`) and the
//!   language mapping, parsed out of `src/lang.rs`.
//!
//! Usage: `gen_breaking <cargo-registry-src-dir> <repo-root>`
//! (see `scripts/gen_breaking.sh`).

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use icu_properties::props::LineBreak;
use icu_properties::{CodePointMapData, PropertyNamesShort};
use icu_provider::buf::AsDeserializingBufferProvider;
use icu_provider::prelude::*;
use icu_provider_blob::BlobDataProvider;
use icu_segmenter::provider::{Baked, BreakState, RuleBreakData, SegmenterBreakLineV1};

const HEADER: &str = "// Generated by oracle/src/bin/gen_breaking.rs. Do not edit.\n\n";

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let registry = PathBuf::from(&args[1]);
    let root = PathBuf::from(&args[2]);

    gen_bidi(&registry.join("unicode-bidi-0.3.18"), &root.join("bidi/tables_gen.mbt"));
    gen_linebreak(
        &registry.join("icu_segmenter_data-2.3.0"),
        &root.join("linebreak/tables_gen.mbt"),
        &root.join("linebreak/lstm_gen.mbt"),
    );
    gen_word(
        &registry.join("unicode-segmentation-1.12.0"),
        &root.join("unicode/word_tables_gen.mbt"),
    );
    gen_hypher(&registry.join("hypher-0.1.8"), &root.join("hypher/tries_gen.mbt"));
}

// ---------------------------------------------------------------------------
// Helpers.

/// A token of a Rust literal table: either a char, a word or a nested tuple.
#[derive(Debug, Clone)]
enum Tok {
    Char(u32),
    Word(String),
    Tuple(Vec<Tok>),
}

/// Parse the body of `const <name>: ... = &[ ... ];` into its tuples.
fn rust_table(src: &str, name: &str) -> Vec<Vec<Tok>> {
    let start = src.find(&format!("const {name}")).unwrap_or_else(|| panic!("table {name}"));
    let start = start + src[start..].find("= &[").unwrap() + 4;
    let body = &src[start..];
    let body = &body[..body.find("];").unwrap()];
    let mut chars = body.chars().peekable();
    let mut out = Vec::new();
    while let Some(&c) = chars.peek() {
        if c == '(' {
            chars.next();
            if let Tok::Tuple(items) = parse_tuple(&mut chars) {
                out.push(items);
            }
        } else {
            chars.next();
        }
    }
    out
}

fn parse_tuple(chars: &mut std::iter::Peekable<std::str::Chars>) -> Tok {
    let mut items = Vec::new();
    let mut word = String::new();
    let flush = |word: &mut String, items: &mut Vec<Tok>| {
        let w = word.trim().to_string();
        if !w.is_empty() {
            items.push(Tok::Word(w));
        }
        word.clear();
    };
    while let Some(c) = chars.next() {
        match c {
            '\'' => {
                let mut lit = String::new();
                for c in chars.by_ref() {
                    if c == '\'' {
                        break;
                    }
                    lit.push(c);
                }
                let hex = lit.trim_start_matches("\\u{").trim_end_matches('}');
                items.push(Tok::Char(u32::from_str_radix(hex, 16).unwrap()));
            }
            '(' => {
                // `Some(...)`: keep the word as a wrapper.
                let inner = parse_tuple(chars);
                let w = word.trim().to_string();
                word.clear();
                items.push(Tok::Tuple(vec![Tok::Word(w), inner]));
            }
            ')' => {
                flush(&mut word, &mut items);
                return Tok::Tuple(items);
            }
            ',' => flush(&mut word, &mut items),
            c => word.push(c),
        }
    }
    Tok::Tuple(items)
}

fn tok_char(t: &Tok) -> u32 {
    match t {
        Tok::Char(c) => *c,
        _ => panic!("expected char, got {t:?}"),
    }
}

fn tok_word(t: &Tok) -> &str {
    match t {
        Tok::Word(w) => w,
        _ => panic!("expected word, got {t:?}"),
    }
}

/// Collapse a per-code-point classification into inclusive ranges with a
/// value; `skip` is not stored.
fn valued(f: impl Fn(u32) -> u32, skip: u32) -> Vec<(u32, u32, u32)> {
    let mut out: Vec<(u32, u32, u32)> = Vec::new();
    for cp in 0u32..=0x10FFFF {
        let v = f(cp);
        if v == skip {
            continue;
        }
        if let Some(last) = out.last_mut()
            && last.1 + 1 == cp
            && last.2 == v
        {
            last.1 = cp;
            continue;
        }
        out.push((cp, cp, v));
    }
    out
}

fn emit_valued(out: &mut String, name: &str, doc: &str, r: &[(u32, u32, u32)]) {
    writeln!(out, "///|\n/// {doc}\nlet {name} : FixedArray[Int] = [").unwrap();
    for chunk in r.chunks(4) {
        out.push_str("  ");
        for (a, b, v) in chunk {
            write!(out, "0x{a:X}, 0x{b:X}, {v}, ").unwrap();
        }
        out.push('\n');
    }
    out.push_str("]\n\n");
}

fn emit_ints(out: &mut String, name: &str, doc: &str, ty: &str, v: &[i64]) {
    writeln!(out, "///|\n/// {doc}\nlet {name} : FixedArray[{ty}] = [").unwrap();
    for chunk in v.chunks(16) {
        out.push_str("  ");
        for x in chunk {
            write!(out, "{x}, ").unwrap();
        }
        out.push('\n');
    }
    out.push_str("]\n\n");
}

fn emit_names(out: &mut String, name: &str, names: &[String]) {
    writeln!(out, "///|\nlet {name} : FixedArray[String] = [").unwrap();
    for n in names {
        writeln!(out, "  {n:?},").unwrap();
    }
    out.push_str("]\n\n");
}

const B64: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";

fn base64(data: &[u8]) -> String {
    let mut s = String::with_capacity(data.len().div_ceil(3) * 4);
    for chunk in data.chunks(3) {
        let b = [chunk[0], *chunk.get(1).unwrap_or(&0), *chunk.get(2).unwrap_or(&0)];
        let n = (u32::from(b[0]) << 16) | (u32::from(b[1]) << 8) | u32::from(b[2]);
        s.push(B64[(n >> 18) as usize & 63] as char);
        s.push(B64[(n >> 12) as usize & 63] as char);
        s.push(if chunk.len() > 1 { B64[(n >> 6) as usize & 63] as char } else { '=' });
        s.push(if chunk.len() > 2 { B64[n as usize & 63] as char } else { '=' });
    }
    s
}

/// Emit binary data as a base64 multiline string literal (newlines are
/// ignored by the decoder).
fn emit_blob(out: &mut String, name: &str, doc: &str, data: &[u8]) {
    writeln!(out, "///|\n/// {doc} ({} bytes, base64)\nlet {name} : String =", data.len())
        .unwrap();
    let encoded = base64(data);
    for line in encoded.as_bytes().chunks(96) {
        writeln!(out, "  #|{}", std::str::from_utf8(line).unwrap()).unwrap();
    }
    out.push('\n');
}

fn write(path: &Path, content: &str) {
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, content).unwrap();
    eprintln!("wrote {}", path.display());
}

