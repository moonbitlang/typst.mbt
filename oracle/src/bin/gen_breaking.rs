// unicode-bidi.

const BIDI_CLASSES: [&str; 23] = [
    "AL", "AN", "B", "BN", "CS", "EN", "ES", "ET", "FSI", "L", "LRE", "LRI", "LRO", "NSM",
    "ON", "PDF", "PDI", "R", "RLE", "RLI", "RLO", "S", "WS",
];

fn gen_bidi(krate: &Path, dest: &Path) {
    let src = std::fs::read_to_string(krate.join("src/char_data/tables.rs")).unwrap();
    let mut out = String::from(HEADER);

    let version = src.find("UNICODE_VERSION: (u64, u64, u64) = (").unwrap();
    let version = &src[version + 36..];
    let version = &version[..version.find(')').unwrap()];
    writeln!(out, "///|\n/// The Unicode version of the bidi data (unicode-bidi 0.3.18).").unwrap();
    writeln!(out, "pub let unicode_version : (Int, Int, Int) = ({version})\n").unwrap();

    let classes: Vec<(u32, u32, u32)> = rust_table(&src, "bidi_class_table")
        .iter()
        .map(|t| {
            let cls = tok_word(&t[2]);
            let idx = BIDI_CLASSES.iter().position(|c| *c == cls).unwrap();
            (tok_char(&t[0]), tok_char(&t[1]), idx as u32)
        })
        .collect();
    // Cross-check against the public API.
    for &(lo, hi, v) in &classes {
        for cp in [lo, hi] {
            let c = char::from_u32(cp).unwrap();
            assert_eq!(format!("{:?}", unicode_bidi::bidi_class(c)), BIDI_CLASSES[v as usize]);
        }
    }
    emit_valued(
        &mut out,
        "bidi_class_table",
        "`bidi_class_table` (unicode-bidi 0.3.18); values index `BidiClass` in declaration order. Missing = L.",
        &classes,
    );

    let mut pairs = Vec::new();
    for t in rust_table(&src, "bidi_pairs_table") {
        let open = tok_char(&t[0]);
        let close = tok_char(&t[1]);
        let norm = match &t[2] {
            Tok::Word(w) if w == "None" => -1,
            Tok::Tuple(inner) if tok_word(&inner[0]) == "Some" => match &inner[1] {
                Tok::Tuple(x) => tok_char(&x[0]) as i64,
                other => panic!("{other:?}"),
            },
            other => panic!("{other:?}"),
        };
        pairs.extend([open as i64, close as i64, norm]);
    }
    emit_ints(
        &mut out,
        "bidi_pairs_table",
        "`bidi_pairs_table` (unicode-bidi 0.3.18): `[open, close, normalized opening or -1]`.",
        "Int",
        &pairs,
    );
    write(dest, &out);
}

